_sign = lambda lo, hi: '+' if lo > 0 else '-' if hi < 0 else '0'


def _signed(res, nboot=2000):
    "dict(estimate, ci, sign) from an estimateFn's (dp, mean), or from a frozen interval rule's dict(estimate, ci)."
    est, lo, hi = ((res['estimate'], *res['ci']) if isinstance(res, dict) else
                   bootSeeds(res[0], nboot=nboot) if res[0] else (res[1], NAN, NAN))
    return dict(estimate=est, ci=[lo, hi], sign=_sign(lo, hi))


def forecastSim(effects, cellFn, theta, seeds=SEEDS, estimateFn=estimate, nboot=2000):
    """Fitted, prior-only or unfitted (by `theta`, FR-C3): each represented effect's cells, each (cell, seed) once, through
    `cellFn(arm, fault, N, seed, theta) -> row dict` (one board with the effect's measure; level, N and seed filled in when absent),
    signed by the 95% `bootSeeds` interval. `estimateFn(rows, e)`: (dp, mean), or dict(estimate, ci) for an unpaired rule (P14)."""
    rows, done, out = [], set(), {}
    for e in [e for e in effects if e.represented]:
        for lv, N, s in ((lv, N, s) for lv, N in armCells(e) for s in seeds if (lv, N, s) not in done):
            done.add((lv, N, s))
            rows.append(dict(dict(level=lv, N=N, seed=s), **cellFn(*lv.split('|', 1), N, s, theta)))
        out[e.id] = _signed(estimateFn(rows, e), nboot)
    return out


def forecastPilot(effects, pilotRows, priorRows, estimateFn=estimate):
    """Pilot-only (FR-C3, P22-16, P22-17): each cell from the pilot if it has it, else from `priorRows` (Claude rows from before the
    experiment); `estimateFn(rows, e, paired=False)`'s sign; when not computable, every-design-helps' sign, marked `fallback`."""
    have = {_key(r) for r in pilotRows}
    rows, out = list(pilotRows) + [r for r in priorRows if _key(r) not in have], {}
    for e in effects:
        m = estimateFn(rows, e, paired=False)[1]
        out[e.id] = (dict(estimate=m, sign=_sign(m, m), fallback=False) if np.isfinite(m)
                     else dict(estimate=None, sign=e.naive, fallback=True))
    return out


def forecastNaive(effects):
    "Every-design-helps: each effect's declared naive sign (items where it does not apply are left out)."
    return {e.id: dict(sign=e.naive) for e in effects if e.naive in ('+', '-')}

