def _plain(x):
    "JSON-ready: tuples to lists, numpy scalars to Python, nan to None."
    if isinstance(x, (dict, list, tuple)):
        return {str(k): _plain(v) for k, v in x.items()} if isinstance(x, dict) else [_plain(v) for v in x]
    x = x.item() if isinstance(x, np.generic) else x
    return None if isinstance(x, float) and not np.isfinite(x) else x


def writeForecast(f, path):
    "FR-C5: sorted-key JSON with a trailing newline; returns its SHA-256 (same input, same bytes)."
    b = (json.dumps(_plain(f), sort_keys=True, indent=1) + '\n').encode()
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_bytes(b)
    return hashlib.sha256(b).hexdigest()


SCORE_RULE = ("paper2's rule (P22-9): no call when the Claude 95% interval spans 0; right when it excludes 0 on the forecast's "
              'side; wrong when it excludes 0 and the forecast has the other sign or 0')


def call(sign, ci):
    "SCORE_RULE for one forecast sign and one Claude interval: 'right', 'wrong' or 'no call'."
    obs = _sign(*[_f(c) for c in ci])
    return 'no call' if obs == '0' else 'right' if sign == obs else 'wrong'


def scoreExperiment(predPath, observed, path=None):
    """FR-D1: `observed` {id: (estimate, ci)} from the experiment's report. Per item and forecaster: right, wrong or no call (a
    simulator on an unrepresented item: 0). Counts on the common set, on all items, and (P22-17) fitted and pilot-only on the items
    pilot-only computes. Writes `<exp>_score.json` beside the forecast (or at `path`); returns the score."""
    predPath = Path(predPath)
    f, res = json.loads(predPath.read_text()), {}
    for k, it in sorted(f['items'].items()):
        est, ci = observed[k]
        L = it['lines']
        r = {ln: call(L[ln]['sign'] if ln in L else '0', ci) for ln in LINES if ln in L or (ln in SIMS and not it['represented'])}
        res[k] = dict(estimate=est, ci=list(ci), observed=_sign(*[_f(c) for c in ci]), represented=it['represented'],
                      fallback=bool(L.get('pilotOnly', {}).get('fallback')), result=r)
    cnt = lambda ids, ls=LINES: {k: {o: sum(res[i]['result'].get(k) == o for i in ids) for o in ('right', 'wrong', 'no call')} for k in ls}
    common = [k for k in res if res[k]['represented']]
    computed = [k for k in res if 'pilotOnly' in res[k]['result'] and not res[k]['fallback']]
    out = dict(exp=f['exp'], forecast=predPath.name, rule=SCORE_RULE, items=res,
               common=cnt(common), all=cnt(list(res)), pilotComputed=cnt(computed, ('fitted', 'pilotOnly')),
               n=dict(common=len(common), all=len(res), pilotComputed=len(computed)))
    name = predPath.name.replace('_predictions.json', '_score.json')
    writeForecast(out, path or predPath.parent / (name if name != predPath.name else predPath.stem + '_score.json'))
    return out
