def projectHours20(turnsPerHour=40_000, loadHours=0.4, unitsPerHour=12.0):
    """A100 hours (README's derivation): honest agent turns / turnsPerHour (Phase 17's step 0, model loading included) for
    part b's new cells and, plus loadHours of model loading, the bridge check; oneBoard: re-running the one-board arm."""
