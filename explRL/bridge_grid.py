def c1Estimate(cells, perCall):
    """Calls (cellCalls: 1,920 per liar board, 2,560 per clean board) and cost per arm. perCall: dollars per call, one number
    or {arm: dollars}; an arm without its own (the pilot has no squads or bridge2 board) takes the highest given (conservative)."""
    pc = perCall if isinstance(perCall, dict) else {}
    top = max(pc.values()) if pc else float(perCall)
    by = {}
    for c in cells:
        a, n = arm20(c), cellCalls(c)
        d = by.setdefault(a, dict(boards=0, calls=0, cost=0.0))
        d['boards'], d['calls'], d['cost'] = d['boards'] + 1, d['calls'] + n, d['cost'] + n * float(pc.get(a, top))
    return dict(boards=len(cells), calls=sum(d['calls'] for d in by.values()), cost=sum(d['cost'] for d in by.values()), byArm=by)


