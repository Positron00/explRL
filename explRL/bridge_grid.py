def reusedPartB(root=COLAB, models=PARTB_MODELS, files=PARTB_FILES):
    """The one-board rows of part b ('|n32', '|n32liar') from Phase 17's evaluation CSVs (raw strings), after a check that each
    row's configuration columns equal the matching new squads-of-4 cell's apart from `squads` and the level (ValueError)."""
    new = {(c['level'].replace('sq4', ''), c['seed']): _strRow(c) for c in squadEvalSuite(models)}
    out = []
    for m in models:
        for r in csv.DictReader(open(Path(root) / files[m], newline='')):
            if r['level'] not in (f'{m}|n32', f'{m}|n32liar'):
                continue
            want = new[(r['level'], int(float(r['seed'])))]
            bad = {k: (r.get(k), v) for k, v in want.items() if k not in ('level', 'world.squads') and
                   (_num(r.get(k)) != _num(v))}
            if bad:
                raise ValueError(f"{r['level']} seed {r['seed']}: configuration differs from the squads-of-4 cell: {bad}")
            out.append(r)
    if len(out) != 20 * len(models):
        raise ValueError(f'expected {20 * len(models)} one-board rows, found {len(out)}')
    return out


def _num(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return v


