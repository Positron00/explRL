def _table(counts, lines):
    head = '| Forecaster | Right | Wrong | No call |\n|---|---|---|---|\n'
    return head + ''.join(f"| {k} | {counts[k]['right']} | {counts[k]['wrong']} | {counts[k]['no call']} |\n" for k in lines if k in counts)


