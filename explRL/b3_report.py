def mcnemar(a, b):
    "Exact two-sided McNemar p of two forecasters' right/not-right lists over the same items (binomial on the discordant pairs)."
    n10, n01 = sum(x and not y for x, y in zip(a, b)), sum(y and not x for x, y in zip(a, b))
    n = n10 + n01
    return 1.0 if n == 0 else min(1.0, 2 * sum(comb(n, i) for i in range(min(n10, n01) + 1)) / 2 ** n)


def _cnt(items, lines=LINES):
    return {k: {o: sum(i['result'].get(k) == o for i in items) for o in ('right', 'wrong', 'no call')} for k in lines}


def poolScores(paths):
    "FR-D3: the items of every score file (scoreExperiment's), with counts on the common set and on all items, per experiment and pooled."
    items, byExp = [], {}
    for p in paths:
        s = json.loads(Path(p).read_text())
        byExp[s['exp']] = dict(common=s['common'], all=s['all'])
        items += [dict(exp=s['exp'], id=k, observed=v['observed'], represented=v['represented'], fallback=v['fallback'],
                       result=v['result']) for k, v in sorted(s['items'].items())]
    common = [i for i in items if i['represented']]
    comp = [i for i in items if 'pilotOnly' in i['result'] and not i['fallback']]
    return dict(experiments=sorted(byExp), byExp=byExp, items=items, common=_cnt(common), all=_cnt(items),
                pilotComputed=_cnt(comp, ('fitted', 'pilotOnly')), conclusive=sum(i['observed'] != '0' for i in common))


def forecastStatus(root='.', forecasts=FORECASTS):
    "{exp: dict(forecast, score)}: whether each experiment's frozen forecast and its score file exist."
    R = Path(root)
    return {e: dict(forecast=(R / p).exists(), score=(R / p.replace('_predictions', '_score')).exists()) for e, p in forecasts.items()}


def gateB3(pooled, plan=None, status=None):
    """FR-D3, H22-1 by P22-10's counting rule on the pooled common set; McNemar beside it; H22-4 descriptive. Refuses while an
    experiment of plan['experiments'] (simulated or two-line) has a frozen forecast but no score (status: forecastStatus() by
    default); 'too few calls to read' below plan's minimum."""
    plan = plan or B3_PLAN
    status = forecastStatus() if status is None else status
    exps = plan['experiments']['simulated'] + plan['experiments']['twoLines']
    missing = [e for e, s in sorted(status.items()) if e in exps and s['forecast'] and not s['score']]
    if missing:
        return dict(verdict='refused', missing=missing, note='every frozen forecast must be scored before the gate (FR-D3)')
    concl = [i for i in pooled['items'] if i['represented'] and i['observed'] != '0']
    right = {k: pooled['common'][k]['right'] for k in LINES}
    out = dict(conclusive=len(concl), minimum=plan['gate']['minConclusive'], right=right,
               wrong={k: pooled['common'][k]['wrong'] for k in LINES},
               mcnemar={a: mcnemar(*[[i['result'].get(k) == 'right' for i in concl] for k in ('fitted', a)]) for a in ALTS},
               H22_4=dict(fitted=right['fitted'], priorOnly=right['priorOnly'], note='descriptive'),
               pilotComputed=pooled['pilotComputed'])
    if len(concl) < plan['gate']['minConclusive']:
        return dict(out, verdict=plan['gate']['below'])
    return dict(out, verdict='passes' if all(right['fitted'] > right[a] for a in ALTS) else 'fails')

