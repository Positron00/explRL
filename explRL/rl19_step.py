class RecordBook:
    """Arm 4's per-agent records in training: one contest.Records per board slot of a step (its key: team size, liar count,
    distinct board, GRPO copy), carried to the next step with the same key, so a sequence keeps its liar slots (a key recurs
    when its board draws that liar count again; Records resets itself after 6 boards). `take` hands out fresh
    copies of the committed records (a rolled-back step replays from the same state); `commit` keeps what the step's
    rollouts added; `save` writes them with the step's checkpoint (records/step-<step>.json), and a resume loads that step's."""
    def __init__(self, out, start=0):
        self.dir, self.state, self.live = Path(out) / 'records', {}, {}
        if start:
            p = self.dir / f'step-{start:04d}.json'
            if not p.exists():
                raise FileNotFoundError(f'no records saved with the step {start} checkpoint ({p})')
            self.state = {tuple(k): v for k, v in json.loads(p.read_text())}

    def take(self, keys, N):
        recs = []
        for k in keys:
            r = Records(N, SEQ)
            if k in self.state:
                r.boards, r.cur = [list(map(dict, b)) for b in self.state[k]['boards']], list(map(dict, self.state[k]['cur']))
            recs.append(r)
        self.live.update(zip(map(tuple, keys), recs))
        return recs

    def commit(self):
        self.state.update({k: dict(boards=r.boards, cur=r.cur) for k, r in self.live.items()})   # keys not played this step keep theirs
        self.live = {}

    def save(self, step):
        self.dir.mkdir(parents=True, exist_ok=True)
        (self.dir / f'step-{step:04d}.json').write_text(json.dumps([[list(k), v] for k, v in sorted(self.state.items())]) + '\n')


def answerStats(cfg, gs):
    """The step's honest answers against the warm start's on the same board types: {answers, answerRef, answerRatio}
    ({} unless the run has the answer halt or the penalty)."""
    if not (getattr(cfg, 'haltAnswers', None) or getattr(cfg, 'sharePenalty', 0.0)):
        return {}
    tab = {tuple(int(x) for x in k): float(v) for k, v in dict(cfg.world)['warmAnswers']}
    a = sum(honestAnswers(bd, c.nLiar) for c, ro in gs for bd in ro.boards)
    ref = sum(tab[boardType(c.N, c.nLiar, bd.life)] for c, ro in gs for bd in ro.boards)
    return dict(answers=int(a), answerRef=float(ref), answerRatio=a / ref if ref else float('nan'))


def haltReason19(history, cfg):
    """haltReason (invalid replies; KL, FIX18's run of steps), then the answer halt: haltAnswers steps in a row whose honest
    answers fall below a third of the warm start's (answerRatio < 1/3). At haltAnswers None: haltReason exactly."""
    r, k = haltReason(history, cfg), getattr(cfg, 'haltAnswers', None)
    if r or not k:
        return r
    last = history[-k:]
    if len(last) == k and all(h.get('answerRatio', 1.0) < 1 / 3 for h in last):
        return f"answers per board below a third of the warm start's for {k} steps (steps {last[0]['step']}-{last[-1]['step']})"
    return None
