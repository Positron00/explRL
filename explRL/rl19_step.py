def threatDraws(cfg, s):
    """[(liars of 16, lifetime)] per distinct board of step s from cfg.threat = (liar counts, lifetimes): two RNGs seeded by
    the step only ([s, 0] for liars, [s, 1] for lifetimes), so arms 2 and 3 draw the same lifetimes and every run the same types."""
    counts, lives = cfg.threat
    a = np.random.default_rng([s, 0]).integers(len(counts), size=cfg.seedsPerStep)
    b = np.random.default_rng([s, 1]).integers(len(lives), size=cfg.seedsPerStep)
    return [(int(counts[x]), int(lives[y])) for x, y in zip(a, b)]


def stepGroups(cfg, s):
    """[(N, nLiar, life, seeds, keys)]: the step's board groups. Without a threat, boardGroups' (life None: the world's) with
    keys (N, nLiar, board); with one, boards of one type (N, liars scaled from 16 to N, lifetime) in a group, keys (N, nLiar, j, copy)
    for distinct board j and GRPO copy (each seed repeated `group` times, the distinct seeds split by mixN as boardGroups splits
    them). The liar count in the key keeps a record sequence's liar slots fixed (records follow keys, RecordBook)."""
