BRIDGE_KEYS = ('couple', 'bridges', 'bridgeGuard')


def dealBridges(N, S, nLiar, guards, perPair=1, guarding=False):
    """[[bridge slots] per squad], squads placed as squadOf (slot i in squad i mod (N // S)); liars the first nLiar slots and
    guards the next `guards` (as dealSquads). Ordinary: the first perPair honest non-guard slots of each squad, by slot order;
    guarding: the first guard slot of each squad (perPair must be 1). ValueError if a squad lacks the slots."""
    if perPair not in (0, 1, 2) or guarding and perPair != 1:
        raise ValueError(f'bridges: perPair must be 0, 1 or 2 (1 when guarding), got {perPair!r}')
    n, (_, gs) = N // S, dealSquads(N, S, nLiar, guards)
    out = [(gs[s] if guarding else [i for i in range(nLiar + guards, N) if i % n == s])[:perPair] for s in range(n)]
    if any(len(b) < perPair for b in out):
        raise ValueError(f"bridges: a squad has fewer than {perPair} {'guard' if guarding else 'honest non-guard'} slots")
    return out


def checkBridge(world, N=None, nLiar=0):
    "The bridge keys' checks: couple needs squads, bridges couple, bridgeGuard bridges = 1 and guards; dealBridges must succeed."
    if not any(k in world for k in BRIDGE_KEYS):
        return True
    S, b = world.get('squads'), world.get('bridges', 0)
    if world.get('couple') and not (S and 0 < world['couple'] <= 1):
        raise ValueError('couple needs squads and a value in (0, 1]')
    if 'couple' not in world or b and not world.get('couple') or world.get('bridgeGuard') and (b != 1 or not world.get('guards', 0)):
        raise ValueError('a bridge key needs couple (no silent default); bridges need couple > 0; bridgeGuard needs bridges = 1 and guards')
