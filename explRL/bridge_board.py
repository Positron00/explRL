class BridgeBoardEnv(ColonyBoardEnv):
    """ColonyBoardEnv in squads (S) with coupled subtasks and bridges. couple (0.25): each squad's every 1/couple-th assigned
    subtask is coupled to squad (s + 1) mod n: clue 0 dealt within s, clue 1 within s + 1 (two holders each, _pick on rngDeal).
    Mirrors: squad s + 1 sees each coupled subtask of s as a mirror; its agents' shares there go to mirrorLog. bridges (0, 1, 2
    per pair) and bridgeGuard: bridge slots from dealBridges; a bridge's share on a coupled subtask of a value in that subtask's
    mirrorLog is a relay (relayLog). Every other behaviour is ColonyBoardEnv's."""
    def __init__(self, seed, nAgents, couple=0.25, bridges=0, bridgeGuard=False, nLiar=0, **kw):
        self.couple, self.nLiar, S = float(couple or 0), int(nLiar), kw.get('squads')
        g = len(frozenset(kw.get('guardSlots', ())))
        checkBridge(dict(couple=self.couple, bridges=bridges, bridgeGuard=bridgeGuard, squads=S, guards=g), nAgents, self.nLiar)
        if frozenset(kw.get('guardSlots', ())) != frozenset(range(self.nLiar, self.nLiar + g)):
            raise ValueError('bridges: guard slots must follow the nLiar liar slots')
        self.bridges = dealBridges(int(nAgents), int(S), self.nLiar, g, int(bridges), bool(bridgeGuard)) if S else []
        self.bridgeSet, self.bridgeGuard = frozenset(a for b in self.bridges for a in b), bool(bridgeGuard)
        super().__init__(seed, nAgents, **kw)

    def reset(self, seed, nAgents):
        "mirrorLog, relayLog, coupled {k: (s, s2)} and nAssigned per squad, then the base reset (which deals 2N + 2 subtasks)."
        self.nAssigned, self.coupled, self.mirrorLog, self.relayLog = [0] * self.nSquads, {}, [], []
        super().reset(seed, nAgents)

    def _deal(self):
        "Once per subtask, from ClueBoardEnv._new (self._squad and self.serial set): every 1/couple-th of a squad's is coupled."
        s = self._squad
        self.nAssigned[s] += 1
        if not self.couple or self.nAssigned[s] % round(1 / self.couple):
            return super()._deal()
        s2 = self.coupled.setdefault(self.serial, (s, (s + 1) % self.nSquads))[1]
        slots = lambda q: [a for a in range(self.nAgents) if a % self.nSquads == q]
        held, out = {a: 0 for a in slots(s) + slots(s2)}, []
        for j in range(self.m):                       # as ColonyBoardEnv._deal, clue 1 from s2's slots, the others from s's
            sl, hs = slots(s2 if j == 1 else s), set()
            groups = ([[a for a in sl if a in self.guardSet], [a for a in sl if a not in self.guardSet]]
                      if self.guardDeal else [sl] * min(self.r, len(sl)))
            for g in groups:
                a = self._pick([a for a in g if a not in hs], held)
                hs.add(a)
                held[a] += 1
            out.append(frozenset(hs))
        return out

    def mirrors(self, i, every=None):
        """The open coupled subtasks k whose s2 is i's squad and whose clue 1 i holds (P20-16); every (default: i is a liar
        slot, P20-5): all of them."""
        q, every = i % self.nSquads, i < self.nLiar if every is None else every
        return [k for k in self.open if k in self.coupled and self.coupled[k][1] == q
                and (every or i in self.tasks[k].holders[1])]

    def mirrorTally(self, k):
        "tally's format, {k: {j: [(r, senders, newest)]}} ({} with no posts), from mirrorLog: mirror posts never reach the channel."
        vals, out = {}, {}
        for t, a, k2, j, r, *_ in self.mirrorLog:
            if k2 == k:
                s, n = vals.get((j, r), (set(), -1.0))
                vals[(j, r)] = (s | {a}, max(n, t))
        for (j, r), (s, n) in vals.items():
            out.setdefault(k, {}).setdefault(j, []).append((r, frozenset(s), n))
        for j in out.get(k, {}):
            out[k][j].sort(key=lambda x: (-len(x[1]), -x[2], x[0]))
        return out

    def bridgeOf(self, i):
        "(s, s2) if agent i is a bridge (from s2 = s + 1 to its squad s), else None."
        s = i % self.nSquads
        return (s, (s + 1) % self.nSquads) if i in self.bridgeSet else None

    def apply(self, i, action, t):
        """A share of clue 1 on one of mirrors(i) goes to mirrorLog (a 'shared' ledger row, counts['shares']; not shareLog);
        a bridge's share on its pair's coupled k of a value in k's mirrorLog is also logged in relayLog with its source post
        (the value's first mirror post). Opening or answering a mirror stays invalid (ColonyBoardEnv: another squad's subtask)."""
        kind, arg = action
        if kind == 'share' and int(arg[0]) in self.coupled:
            self.advance(t)                                    # mirrors(i) lists the subtasks open at t
            k, j, r = (int(x) for x in arg)
            if j == 1 and k in self.mirrors(i):
                red = any(m[2] == k and m[3] == j for m in self.mirrorLog)
                self.mirrorLog.append((float(t), i, k, j, r, red, self.tasks[k].task.clue(j)[1] != r))
                self.counts['shares'] += 1
                rew, dur, _, info = super().apply(i, ('wait', None), t)   # the turn as a wait (time, contest view, reward) ...
                self.ledger[-1] = self.ledger[-1][:4] + (k,) + self.ledger[-1][5:]   # ... its ledger row on k
                return rew, dur, k, dict(info, task=k, result='shared')
            relay = self.coupled[k] == self.bridgeOf(i)                     # a bridge's share on its pair's subtask
            src = next((m for m in self.mirrorLog if m[2:5] == (k, j, r)), None) if relay else None
            n, out = len(self.shareLog), super().apply(i, action, t)
            if src is not None and len(self.shareLog) > n:
                self.relayLog.append((float(t), i, k, j, r, src))
            return out
        return super().apply(i, action, t)

    def _creditTo(self, i, k):
        """[(agent, d)], each paid credit * delta / d: the base agents with d = their number; under 'credit' and 'contest' a relay's
        share goes half to the bridge and half to its source poster, the first true poster on the mirror (P20-12)."""
        out = []
        for j, hs in enumerate(self.tasks[k].holders):
            if i not in hs:
                s = next((s for s in self.shareLog if s[2] == k and s[3] == j and not s[6] and s[1] != i), None)
                if s is not None and s[1] not in [x[0] for x in out]:
                    src = relaySource(self, s)
                    out.append([s[1]] + ([src[1]] if src is not None else []))
        return [(a, len(out) * len(to)) for to in out for a in to]

    def _reward(self, i, delta, k=None, solved=False):
        if not (self.scheme in ('credit', 'contest') and solved and (to := self._creditTo(i, k))):
            return super()._reward(i, delta, k, solved)
        for a, d in to:
            self.pending[a] += self.credit * delta / d
        self.pending[i] += (1 - self.credit) * delta
        r, self.pending[i] = float(self.pending[i]), 0.0
        return r

    def viewFor(self, i):
        return BridgeView(self, i)


class BridgeView(SquadView):
    "SquadView plus `mirrors` (agent i's mirrors, with the cross clues it holds) and, for a bridge, `pair` (mirror tallies)."
    def __init__(self, board, i):
        super().__init__(board, i)
        self.__dict__['_i'] = i

    def mirrors(self, i=None, every=None):
        "The board's mirrors(i): agent i's mirror subtasks (holders of the cross clue; liars: all)."
        return self._b.mirrors(self._i if i is None else i, every)

    def crossClues(self):
        "{k: (p, r)}: the cross clue agent i holds on each of its mirrors."
        return {k: self._b.tasks[k].task.clue(1) for k in self.mirrors() if self._i in self._b.tasks[k].holders[1]}

    @property
    def pair(self):
        "For a bridge, tally's format over its pair's open coupled subtasks with mirror posts; None for anyone else."
        p, out = self._b.bridgeOf(self._i), {}
        if p is None:
            return None
        for k in self._b.open:
            if self._b.coupled.get(k) == p:
                out.update(self._b.mirrorTally(k))
        return out


def relaySource(board, post):
    "The mirrorLog post a relay copied (post: its shareLog or relayLog entry, (t, i, k, j, r, ...)), or None."
    return next((x[5] for x in getattr(board, 'relayLog', ()) if x[:5] == tuple(post[:5])), None)
