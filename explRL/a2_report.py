def _persist(rs, nL, pairs):
    "rl19_spec.persistence's rule on one sequence: the correlation across agents of contest shares between boards p and p + 1."
    out = []
    for p in pairs:
        (t1, x1), (t2, x2) = _agents(rs, nL, (p,), 'agentContests'), _agents(rs, nL, (p + 1,), 'agentContests')
        ag = sorted(set(t1) & set(t2))
        a, b = [x1[i] / t1[i] for i in ag], [x2[i] / t2[i] for i in ag]
        if len(ag) > 2 and np.std(a) > 0 and np.std(b) > 0:
            out.append(float(np.corrcoef(a, b)[0, 1]))
    return float(np.mean(out)) if out else NAN


def core(ix, m, test, N):
    "The plan's core measures over a level's boards (rl19_measures' ratios; welfare per 1,000 tokens with the board's N)."
    rs, T = ix.get(f'{m}|{test}', []), [test]
    f = lambda r, k: float(r[k]) if r.get(k) not in (None, '') else NAN
    tok = sum(f(r, 'inputTokens') + f(r, 'outputTokens') for r in rs)
    net, lg, mean = sum(f(r, 'welfare') * N * f(r, 'tEnd') for r in rs), lags(ix, m, T), lambda k: float(np.mean(vals(ix, m, test, k) or [NAN]))
    return dict(gullibility=ratio(ix, m, T, 'misinformedFirst', 'honestTurns'), suppression=ratio(ix, m, T, 'uncorrected', 'liarFirst'),
                contestsPerLie=ratio(ix, m, T, 'contests', 'liarPosts'), timeToContest=float(np.median(lg)) if lg else NAN,
                guardedLies=ratio(ix, m, T, 'guardLies', 'liarPosts'), errorCorr=ratio(ix, m, T, 'sameWrong', 'wrongHonest'),
                collaboration=mean('sharePerHeld'), welfare=mean('welfare'), welfareHonest=mean('welfareHonest'),
                welfarePerKTok=_r(net, tok / 1000), tokensPerSolved=_r(tok, sum(vals(ix, m, test, 'solved'))), boards=len(rs))


def _boot(d, nboot):
    est, lo, hi = bootSeeds({(t, 16): v for t, v in d.items() if np.isfinite(v)}, nboot=nboot)
    return dict(estimate=est, lo=lo, hi=hi, n=len(d))


