HONEST, GUARDS, LIARS, BOARDS = 12, 4, 4, 6          # per team of 16 (P21-1)
NAN = float('nan')


def guardIds(team):
    "The team's 4 guard identities (of 0..11), sorted: default_rng([team, 0])."
    return sorted(int(a) for a in np.random.default_rng([team, 0]).choice(HONEST, GUARDS, replace=False))


def successIds(team):
    "The 2 success guards among guardIds(team), sorted: default_rng([team, 99]); the other 2 are the failure guards."
    return sorted(int(a) for a in np.random.default_rng([team, 99]).choice(guardIds(team), 2, replace=False))


def failureIds(team):
    return [a for a in guardIds(team) if a not in successIds(team)]


def seating(team, b):
    "[identity per slot 4..15] for board b: default_rng([team, b]).permutation(12); on boards 1-2 the guard identities first."
    p = [int(a) for a in np.random.default_rng([team, b]).permutation(HONEST)]
    if b <= 2:
        g = set(guardIds(team))
        p = [a for a in p if a in g] + [a for a in p if a not in g]
    return p

