def a2Columns(cfg, board):
    """Phase 21's columns for one board: per identity (JSON, identity order) guarding, contests, followed, watchers, held
    shares, answers, turns; the success and failure guards' mean guarding; the liars' false posts on clues a success or a
    failure guard holds; the row keys agents (per slot: the liar's slot, or identity + 4), pos (board - 1) and seqId (team)."""
    w, nL, N = cfg.world, cfg.nLiar, cfg.N
    seat = [int(a) for a in (w.get('seat') or range(N - nL))]
