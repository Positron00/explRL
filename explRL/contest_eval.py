def contestsOf(board, nLiar):
    """[(t_c, contester, k, j, t_l)] on a finished board, as ContestLog judges them (any reward scheme): an honest post of a
    clue's true value while the slot shows a false value first posted by a liar (t_l: the first such lie's post)."""
    first, out = {}, []
    for s in board.shareLog:
        t, i, k, j, r, false = s[0], s[1], s[2], s[3], s[4], s[6]
        lies = sorted(tt for rr, (a, tt, f) in first.get((k, j), {}).items() if a < nLiar and f)
