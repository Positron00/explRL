def waitAnswers(board, nLiar, answers, guards=0):
    """The waiting rate's counts (waited, used) over the non-guard honest agents' answers: `used`, answers that use a posted
    value (agree, mod p_j, with a value posted before them for a clue j the agent does not hold; a refused submission is no
    answer); `waited`, those whose every used value had at least two senders when the answer was given."""
    snd, waited, used = {}, 0, 0
    for s in board.shareLog:
        snd.setdefault((s[2], s[3], s[4]), []).append((float(s[0]), s[1]))
    for t, i, k, *_ in board.submits:
        x = answers.get((float(t), i))
        if i < nLiar + guards or isinstance(x, bool) or not isinstance(x, (int, np.integer)):
            continue
        sub, n = board.tasks[k], []
        for j, hs in enumerate(sub.holders):
            if i not in hs:
                got = {a for tt, a in snd.get((k, j, int(x) % sub.task.clue(j)[0]), ()) if _seen((tt, a), t, i)}
                n += [len(got)] if got else []
        used += bool(n)
        waited += bool(n) and min(n) >= 2
    return waited, used


def misinformedFirst(board, nLiar):
    """Honest agents' first wrong answers to a subtask made while misinformed: before the answer, a false value was posted
    for one of the subtask's clues the agent does not hold."""
    fv, first, n = {}, set(), 0
    for s in board.shareLog:
        if s[6]:
            fv.setdefault((s[2], s[3]), []).append((float(s[0]), s[1]))
    for t, i, k, _, res in board.submits:
        if i < nLiar or res != 'wrong' or (i, k) in first:
            continue
        first.add((i, k))
        n += any(i not in hs and any(_seen(p, t, i) for p in fv.get((k, j), ())) for j, hs in enumerate(board.tasks[k].holders))
    return n


def uncorrected(board, nLiar):
    "(liarFirst, uncorrected): clues whose first posted value was a liar's false one, and those no honest agent later posted truly."
    first, fixed = {}, set()
    for s in board.shareLog:
        key = (s[2], s[3])
        if key not in first:
            first[key] = s[1] < nLiar and s[6]
        elif first[key] and s[1] >= nLiar and not s[6]:
            fixed.add(key)
    lf = [key for key, v in first.items() if v]
    return len(lf), sum(key not in fixed for key in lf)


def sameWrong(board, nLiar, answers):
    "(wrong, repeated): honest wrong answers of known value, and those repeating a wrong value another honest agent gave the subtask earlier."
    seen, wrong, again = {}, 0, 0
    for t, i, k, _, res in board.submits:
        x = answers.get((float(t), i))
        if i < nLiar or res != 'wrong' or x is None:
            continue
        wrong += 1
        again += any(a != i for a in seen.get((k, str(x)), ()))
        seen.setdefault((k, str(x)), set()).add(i)
    return wrong, again


