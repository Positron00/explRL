def bridgeStepStats(gs, tok=None):
    """A step's rollouts [(LLMConfig, Rollout)] (prompts kept) -> {longestBridge: a bridge's longest prompt plus reply in tokens (as
    pairLengths, eos aside; tok None: 4 characters a token), relaysPerBridgeTurn}; {} when no board has bridges."""
    from explRL.clue_policy import userText
    from explRL.local_policy import promptText
    enc = lambda x: len(tok(x, add_special_tokens=False)['input_ids'])
    n = (lambda s, bl, rep: enc(promptText(tok, s, bl)) + enc(rep)) if tok is not None else \
        (lambda s, bl, rep: (len(s) + 2 + len(userText(bl)) + len(rep)) // 4)
    longest, turns, relays, seen = 0, 0, 0, False
    for _, ro in gs:
        for b, bd in enumerate(ro.boards):
            if not getattr(bd, 'bridgeSet', None):
                continue
            seen, relays = True, relays + len(bd.relayLog)
            turns += sum(1 for row in bd.ledger if row[0] in bd.bridgeSet)
            for i in bd.bridgeSet:
                for (s, bl), x in zip(ro.prompts[b][i], ro.logs[b][i]):
                    longest = max(longest, n(s, bl, x.get('response') or ''))
    return dict(longestBridge=int(longest), relaysPerBridgeTurn=relays / turns if turns else NAN) if seen else {}
