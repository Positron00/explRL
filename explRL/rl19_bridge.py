def relayPosters(board):
    "{(t, bridge, k, j, r): the source post's poster} for every relay on the board (relayLog; {} on other boards)."
    return {tuple(x[:5]): x[5][1] for x in getattr(board, 'relayLog', ())}


class BridgeContestLog(ContestLog):
    """ContestLog on a bridge board (T5a; P20-12, and P23-8 as the user kept it). A relayed value is its source poster's, looked
    up when a contest is judged (relayLog is written after the relay's own onShare), so a relayed liar's value is a lie on the
    receiving squad's board and contesting it there pays, as any contest. A border contest: the first true mirror post, by an
    honest holder, while the mirror shows a false value a liar posted there first and no true value (one per slot, so repeated
    posts cannot farm it). Its watchers are the receiving squad's honest agents without the clue that were shown that mirror
    lie before any true value of the slot: on their own board through a relay, or, for the pair's bridge, on the mirror. A
    watcher's later correct solve pays the border contester as any contest pays (the user, 2026-11-12). Board watchers
    (`sawLie`) and border watchers (`sawBorder`) are kept apart."""
    def __init__(self, board, liarSlots, contestSlots, halfLife=4.0):
        super().__init__(board, liarSlots, contestSlots, halfLife)
        self.border, self.sawBorder, self.borderTrue = [], {}, set()   # border contests' indices; {(k, j): {i: t}}; {(i, k, j)}
        self.mirrorFirst, self._src = {}, (0, {})                       # {(k, j): {r: (poster, t)}}; relayPosters by relayLog length

    def _relays(self):
        n = len(self.board.relayLog)
        if self._src[0] != n:
            self._src = (n, relayPosters(self.board))
        return self._src[1]

    def lies(self, k, j):
        "[(t, r, liar)]: the slot's false values on the board first posted by a liar or relayed from a liar's mirror post."
        tr, src = self._true(k, j), self._relays()
        out = [(t, r, src.get((t, a, k, j, r), a)) for r, (a, t) in self.first.get((k, j), {}).items() if r != tr]
        return sorted(x for x in out if x[2] in self.liars)

    def mirrorLies(self, k, j):
        "[(t, r, liar)]: the false values first posted on the slot's mirror by a liar, oldest first."
        tr = self._true(k, j)
        return sorted((t, r, a) for r, (a, t) in self.mirrorFirst.get((k, j), {}).items() if a in self.liars and r != tr)

    def onShown(self, t, i, shown):
        """ContestLog.onShown on the board (relay-aware lies); then the border watchers: a mirror lie shown to i through a relay
        on its board, or on the mirror when i is the pair's bridge, before any true value of the slot."""
        super().onShown(t, i, shown)
        if i in self.liars:
            return
        b, src, p = self.board, self._relays(), self.board.bridgeOf(i)
        mir = {(k, j): set(v) for (k, j), v in self.mirrorFirst.items() if p is not None and k in b.open and b.coupled.get(k) == p}
        for (k, j) in set(mir) | {key for key in shown if key[0] in b.coupled}:
            if (i, k, j) in self.borderTrue:
                continue
            onBoard = shown.get((k, j), set())
            relayed = {r for r, (a, tt) in self.first.get((k, j), {}).items() if r in onBoard and (tt, a, k, j, r) in src}
            if self._true(k, j) in onBoard | mir.get((k, j), set()):
                self.borderTrue.add((i, k, j))
            elif i not in b.tasks[k].holders[j] and any(r in relayed | mir.get((k, j), set()) for _, r, _ in self.mirrorLies(k, j)):
                self.sawBorder.setdefault((k, j), {}).setdefault(i, float(t))

    def onMirror(self, t, i, k, j, r, true):
        "Agent i posts r on k's mirror at t, judged before the post counts: a border contest if it is the first true value against a mirror lie."
        lies, s, first = self.mirrorLies(k, j), self.board.coupled[k][0], self.mirrorFirst.setdefault((k, j), {})
        if true and lies and i not in self.liars and self._true(k, j) not in first:
            w = {a: None for a in self.sawBorder.get((k, j), {}) if a != i and a % self.board.nSquads == s and (a, k, j) not in self.borderTrue}
            self.border.append(len(self.contests))
            self.contests.append(Contest(float(t), i, k, j, lies[0][0], lies[0][1], lies[0][2], w))
        first.setdefault(int(r), (i, float(t)))

