class SubRecords:
    "A Records seen through a slot map (a board with agents removed): slot i is agent slotMap[i]."
    def __init__(self, rec, slotMap):
        self.rec, self.map = rec, list(slotMap)

    def line(self, i):
        return self.rec.line(self.map[i])

    def addBoard(self, board, slots):
        net, log = board.netByAgent(), getattr(board, 'contestLog', None)
        won = log.earned(board.nAgents) if log is not None else [0.0] * board.nAgents
        for i in slots:
            self.rec.add(self.map[i], 'answers', net[i])
            self.rec.add(self.map[i], 'contests', won[i])
        self.rec.endBoard()


def topContesters(counts, nLiar, n):
    "The n honest agents with the most contests (ties: the lower slot)."
    return sorted(range(nLiar, len(counts)), key=lambda i: (-counts[i], i))[:n]


def runSequences(cells, policyFor, logDir=None):
    """Play seqCells' sequences, every sequence of a level in one batch per board position, each with its own Records (per
    agent, when the cells ask for records). On a removal level the N // 4 agents with the most contests on boards 1-3 sit
    out boards 4-5 (the board has N - N // 4 slots, the same number of squads) and return for board 6. Rows: cellRow plus
    seqId, pos and agents (JSON: the original agent of each slot)."""
    rows, levels = [], {}
    for c in cells:
        levels.setdefault(c['level'], []).append(c)
    for cs in levels.values():
        base, sq = LLMConfig.fromDict(cs[0]['cfg']), cs[0]['seq']
        N, nl, seqs = base.N, base.nLiar, sorted({c['seq']['id'] for c in cs})
        at = {(c['seq']['id'], c['seq']['pos']): c for c in cs}
        recs = {sd: Records(N, SEQ) for sd in seqs} if sq['records'] else None
        counts, maps = {sd: np.zeros(N) for sd in seqs}, {sd: list(range(N)) for sd in seqs}
        policies, memory = policyFor(cs[0])
        for p in range(SEQ):
            drop = sq['remove'] and p in (3, 4)
            for sd in seqs:
                out = topContesters(counts[sd], nl, N // 4) if drop else []
                maps[sd] = [i for i in range(N) if i not in out]
            cfg = base
            if drop:
                n2 = N - N // 4
                cfg = LLMConfig.fromDict({**cs[0]['cfg'], 'N': n2, 'world': {**base.world, 'squads': n2 // (N // base.world['squads'])}})
            rl = [recs[sd] if not drop else SubRecords(recs[sd], maps[sd]) for sd in seqs] if recs else None
            ro = rollout(cfg, [at[(sd, p)]['seed'] for sd in seqs], policies, scriptedFaults(cfg.world, nl), memory, records=rl)
            for b, (sd, r) in enumerate(zip(seqs, coopRows(cfg, ro))):
                if p < 3:
                    for c in contestsOf(ro.boards[b], nl):
                        counts[sd][maps[sd][c[1]]] += 1
                row = dict(cellRow(at[(sd, p)], cfg, r), seqId=sd, pos=p, agents=json.dumps(maps[sd]))
                rows.append(row)
                if logDir:
                    f = Path(logDir) / (rowKey(row).replace('|', '__') + '.jsonl')
                    f.parent.mkdir(parents=True, exist_ok=True)
                    recsb = sorted((x for lg in ro.logs[b] for x in lg), key=lambda x: (x['t'], x['agent']))
                    f.write_text(''.join(json.dumps(dict(key=rowKey(row), episode=0, **x), sort_keys=True) + '\n' for x in recsb))
    return sorted(rows, key=rowKey)


def evalSequences(cells, models, out, cache=None, logDir=None):
    "As clue_roll.evalModels for sequence cells: per model out/seq_<name>.csv, read back when present (a rerun continues)."
    from explRL.local_policy import LocalPolicy
    from explRL.rl_torch import freeGPU
    out, rows = Path(out), []
    out.mkdir(parents=True, exist_ok=True)
    for name, (path, adapter) in models.items():
        mine, f = [c for c in cells if c['level'].startswith(name + '|') and 'seq' in c], out / f'seq_{name}.csv'
        if f.exists() or not mine:
            rows += readCSV(f) if f.exists() else []
            continue
        engine = LocalPolicy(path, cache=cache)
        pol = engine if adapter is None else LocalPolicy(path, adapter=adapter, cache=cache, share=engine, tokenizer=engine.tok())
        t0 = time.time()
        got = runSequences(mine, lambda c: (pol, 'notes'), logDir)
        writeCSV(got, f)
        rows += got
        print(f'{name}: {len(got)} sequence boards, {time.time() - t0:.0f} s', flush=True)
        freeGPU(*{id(p): p for p in (pol, engine)}.values())
    return sorted(rows, key=rowKey)
