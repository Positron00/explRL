def warmTable(rows, guards=4):
    "WARM_ANSWERS for one squad size and guard count: [((16, liars, lifetime), mean honest answers per board)] from warmCells' rows."
    by = {}
    for r in rows:
        if f'|trainG{guards}L' in r['level']:
            by.setdefault((int(r['N']), int(r['nLiar']), int(float(r['world.life']))), []).append(float(r['honestAnswers']))
    return [(k, float(np.mean(v))) for k, v in sorted(by.items())]


def pilotCells(models, squads, seeds=PILOT19_PLAN['heldOut']):
    "The pilot's held-out boards: 16 agents at 4 liars, guards 4, the chosen squads, lifetime 30, 40 turns ('<model>|pilotL4')."
    return [_cell(m, 'pilotL4', 16, sd, world19e(squads, guards=4), 4) for m in models for sd in seeds]


def pilotGain(rows, model, warm='warm'):
    "The selection rule's gain: mean honest welfare (welfareHonest) of the model minus the warm start's on the pilot boards."
    v = lambda m: float(np.mean([float(r['welfareHonest']) for r in rows if r['level'] == f'{m}|pilotL4']))
    return v(model) - v(warm)

