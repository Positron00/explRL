def gateC1b(rows, plan=C1B_PLAN, nboot=2000, metric='honestPooled'):
    """Gate C1b over the 8 paired boards (seeds 1800-1807). Part (i): bridgeFix - bridge1 in `metric`, one-sided exact sign-flip,
    passes at p < alpha with a positive estimate. Part (ii): bridgeFix - bridge1 in contamination, holds when upperBound
    (95th percentile of the paired bootstrap means) < margin. Verdict (P23-7): passes, noBridges (ii fails) or ask (i fails,
    ii holds), with what it decides."""
    G, s8 = plan['gate'], set(plan['seeds']['eight'])
    i = _test(_d(rows, 'bridgeFix', 'bridge1', metric, seeds=s8), nboot)
    i['passes'] = bool(i['p'] < G['alpha'] and i['estimate'] > 0)
    c = _d(rows, 'bridgeFix', 'bridge1', G['safety'], seeds=s8)
    ii = dict(_test(c, nboot, 'less'), upper=upperBound(c, nboot, G['quantile']), margin=G['margin'])
    ii['holds'] = bool(ii['upper'] < G['margin'])
    v = 'passes' if i['passes'] and ii['holds'] else 'noBridges' if not ii['holds'] else 'ask'
    return dict(metric=metric, i=i, ii=ii, passes=v == 'passes', verdict=v, decides=G['decides'][v])


