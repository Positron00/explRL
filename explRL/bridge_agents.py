def parseBridge(env, parsed, i):
    """TextClueEnv.parse's bridge cases -> (action, report, valid), or None for parse's own path. A share on one of i's
    mirrors: valid at the cross clue's true residue from a holder (an adaptive liar: any residue), with report None, so
    nothing reaches the channel; anything else there is invalid. A bridge's share on its pair's open coupled subtask of a
    value posted on the mirror (any value, P20-4): a relay, valid and posted as an ordinary share."""
    b = env.world
    if not isinstance(b, BridgeBoardEnv) or not isinstance(parsed, dict) or parsed.get('action') != 'share':
        return None
    k, m = env._task(parsed.get('target', '')), _CLUE.search(str(parsed.get('clue', '')))
    if k not in b.coupled or k not in b.open or m is None:
        return None
    (p, r), (p1, r1) = (int(m.group(1)), int(m.group(2))), b.tasks[k].task.clue(1)
    if k in b.mirrors(i):
        liar = env.fault == 'adaptive' and i < env.nLiar
        ok = p == p1 and (r == r1 and i in b.tasks[k].holders[1] or liar and 0 <= r < p)
        return (('share', (k, 1, r)), None, True) if ok else (('wait', None), None, False)
    if b.bridgeOf(i) == b.coupled[k] and p == p1 and any(x[2:5] == (k, 1, r) for x in b.mirrorLog):
        return ('share', (k, 1, r)), (k, (1, p, r)), True
    return None

