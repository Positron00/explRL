def onMirror(b, i, action):
    "Whether `action` is a share on another squad's coupled subtask, i.e. on one of agent i's mirrors (never posted to the channel)."
    c = action[0] == 'share' and getattr(b, 'coupled', {}).get(int(action[1][0]))
    return bool(c) and c[1] == i % b.nSquads


class RuleBridge(RuleAgent):
    """Mixin for an honest numpy member on a bridge board (`bridgeMembers` builds `Bridge<class>` from its class, so knownFor
    and everything else stay the base agent's: a ColonyAgent on colony arms, flag-aware on failFlag boards). Roles are read at
    act time. A bridge (board.bridgeOf) first relays the leading mirror value (most senders, then earliest) of an open coupled
    subtask of its pair with no value of the cross clue on its board; otherwise it acts as its base agent. Every member, at
    its sharing step, first posts a held cross clue on its mirror when the mirror's leading value is missing, different or
    unconfirmed (ColonyAgent's rule, P22-12). A mirror share is applied to the board only, never posted to the channel."""
    def choose(self, b, t):
        return self._relay(b) or super().choose(b, t)

    def _relay(self, b):
        p = b.bridgeOf(self.id) if hasattr(b, 'bridgeOf') else None
        if p is None or self.channel is None:
            return None
        for k in b.open:
            if b.coupled.get(k) == p and not any(s[2] == k and s[3] == 1 for s in b.shareLog):
                first = {}
                for x in b.mirrorLog:
                    if x[2] == k and x[3] == 1:
                        first.setdefault(x[4], (x[0], set()))[1].add(x[1])
                if first:
                    return ('share', (k, 1, int(min(first, key=lambda r: (-len(first[r][1]), first[r][0])))))
        return None

    def _shareable(self, b, kn, t, *a):
        return self._mirrorShare(b) or super()._shareable(b, kn, t, *a)

    def _mirrorShare(self, b):
        if self.channel is None or self.share == 'never' or not hasattr(b, 'mirrors'):
            return None
        q, held = getattr(self, 'q', Q), getattr(self, 'heldFor', lambda b, k: b.held(self.id, k))
        for k in b.mirrors(self.id, False):
            r, lead = held(b, k).get(1), leading(b.mirrorTally(k), k, 1)
            if r is not None and (lead is None or lead[0] != r or len(lead[1]) < q and self.id not in lead[1]):
                return ('share', (k, 1, r))
        return None

    def post(self, b, action, t):
        if not onMirror(b, self.id, action):
            super().post(b, action, t)


class MirrorLiar(ClueLiar):
    """ClueLiar that counts its squad's mirrors (all of them, P20-5) among its targets: on a lying turn it draws k from
    open + mirrors with rng.integers as ClueLiar does, and on a mirror posts a false residue of clue 1 (to the board only).
    With no mirrors (no bridge key, or none open) its draws are ClueLiar's."""
    def choose(self, b, t):
        mir = b.mirrors(self.id, True) if hasattr(b, 'mirrors') else []
        if not mir:
            return super().choose(b, t)
        self.turn += 1
        cand = [k for k in b.open if k != b.opened[self.id]] + mir
        if self.channel is not None and self.turn % 2:
            k = int(cand[int(self.rng.integers(len(cand)))])
            task = b.tasks[k].task
            j = 1 if k in mir else int(self.rng.integers(len(task.primes)))
            p, r = task.clue(j)
            return ('share', (k, j, int((r + 1 + self.rng.integers(p - 1)) % p)))
        return RuleAgent.choose(self, b, t)

    def post(self, b, action, t):
        if not onMirror(b, self.id, action):
            super().post(b, action, t)


@lru_cache(None)
def _bridged(cls):
    return type('Bridge' + cls.__name__, (RuleBridge, cls), {})


def bridgeMembers(world, members):
    """A run's numpy members on a bridge board (stage4Members' hook, so every numpy path gets it): scripted ClueLiars become
    MirrorLiar; honest rule agents (not liars or mistaken members) gain RuleBridge (their class becomes Bridge<class>).
    InSquad wrappers are kept (their inner member changes); Claude members are left alone. Returns `members`."""
    for m in members:
        x = m.m if isinstance(m, InSquad) else m
        if type(x) is ClueLiar:
            x.__class__ = MirrorLiar
        elif isinstance(x, RuleAgent) and not isinstance(x, (ClueLiar, MistakenAgent, RuleBridge)):
            x.__class__ = _bridged(type(x))
    return members


