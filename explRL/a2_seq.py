def replay21(cfg, seed, client):
    "colony_trace.replay (an LLM cell) with TargetedLiars from world['targets'] ([hit, avoid] slots) and a ContestLog that pays no one -> Replay."
    T, nL, w = cfg.turnsPerAgent(), cfg.nLiar, cfg.world
    b, ch = clueSetup(cfg, seed)
    b.contestLog = ContestLog(b, range(nL), ())                   # watchers only: no contest slot, nothing paid
    client.reserve(estimateCost(cfg.model, 'clue', cfg.N - nL * (w.get('fault') != 'adaptive'), T))
    env = TextClueEnv(b, w.get('hint'), w.get('showOpen', False), **fixOptions(w), nLiar=nL)
    mk = lambda: LLMMember(client, env, ch, cfg.memory, cfg.framing)
    rngs, tg = spawnRngs(seed + 3000, nL), w.get('targets')
    liars = [TargetedLiar(ch, r, *tg) for r in rngs] if tg else faultMembers(w, nL, ch, rngs, mk)
    members = liars + [mk() for _ in range(cfg.N - nL)]
    llm = [m for m in members if isinstance(m, LLMMember)]
    hist = runTurns(stage4Members(w, members), b, T)
    row = dict(episode=0, **clueMetrics(cfg, b, hist, range(nL, cfg.N), T), **llmStats(llm))
    log = [dict(episode=0, **x) for m in llm for x in m.log]
    subs = {(s[0], s[1]) for s in b.submits}
    ans = {(float(r.t), r.agent): r.extras[0] for r in hist.records if (float(r.t), r.agent) in subs and not isinstance(members[r.agent], LLMMember)}
    ans.update({(float(x['t']), x['agent']): x['action'][1] for x in log if x['action'][0] == 'submit'})
    return Replay([row], log, b, ans, nL, T)


def runBoard21(cfg, seed, client):
    "runClue's signature: the board's row with Stage 3's, Phase 19's (contest_eval.contestColumns) and A2's columns, and its turn log."
    rp = replay21(cfg, seed, client)
    return [{**stage3Columns(cfg, rp, seed), **contestColumns(cfg, rp.board, [rp.log]), **a2Columns(cfg, rp.board)}], rp.log


