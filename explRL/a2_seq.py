def _count(n, word):
    return f"{n} {word}{'s' * (n != 1)}"


def historyEntry(row):
    "A finished board's record entry from its row: {board, contests, followed}, per identity."
    return dict(board=int(row['pos']) + 1, contests=json.loads(row['idContests']), followed=json.loads(row['idFollowed']))


def recordLines(arm, history, b, team):
    "((slot, text), ...) for the honest slots of board b of `team` in `arm` (none, shared, own); history: boards 1..b-1."
    T, seat, out = TEXTS21, seating(team, b), []
    if b >= 3 and arm != 'none':
        assert [h['board'] for h in history] == list(range(1, b)), 'history must hold boards 1..b-1'
    for s, a in enumerate(seat):
        txt = T['board'].format(b=b)
        if b >= 3 and arm != 'none':
            nums = [(h['board'], h['contests'][a], h['followed'][a]) if arm == 'own' else
                    (h['board'], sum(h['contests']), sum(h['followed'])) for h in history]
            items = '; '.join(T['item'].format(n=n, who=T['who'][arm], c=_count(c, 'false value'), a=_count(x, 'time'))
                              for n, c, x in nums)
            txt += ' ' + T[arm].format(items=items)
        out.append((LIARS + s, txt))
    return tuple(out)


def boardCell21(team, b, arm, history=()):
    """Board b of `team`'s sequence (seed 10 * team + b). Boards 1-2: Stage 1's colonyGuards cell (4 guards), targeted
    liars against the seated success and failure guards, the board line; level 'common|b<b>', the same in every arm.
    Boards 3-6: Stage 3's colonyVolunteer cell (ClueLiars), the arm's record; level '<arm>|b<b>'."""
    seed, seat = 10 * team + b, seating(team, b)
    slot = {a: LIARS + s for s, a in enumerate(seat)}
    if b <= 2:
        c = colonyCell('a2', 'colonyGuards', 16, seed, 'independent')
        extra = dict(targets=[sorted(slot[a] for a in successIds(team)), sorted(slot[a] for a in failureIds(team))])   # [hit, avoid]
    else:
        c, extra = colonyCell('a2', 'colonyVolunteer', 16, seed, 'independent', arms=ARMS3), {}
    c['cfg']['world'].update(team=team, board=b, seat=seat, slotLines=recordLines('none' if b <= 2 else arm, history, b, team), **extra)
    c['level'] = f"{'common' if b <= 2 else arm}|b{b}"
    return c

