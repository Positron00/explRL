class TargetedLiar(ClueLiar):
    "ClueLiar's cadence; lies on a clue a `hit` slot holds and no `avoid` slot holds, else on any clue no `avoid` slot holds."
    def __init__(self, channel, rng, hit=(), avoid=()):
        super().__init__(channel, rng)
        self.hit, self.avoid = frozenset(hit), frozenset(avoid)

    def candidates(self, b):
        "The (k, j) it may lie on now: the preferred ones (a hit slot holds), else every clue no avoid slot holds."
        ok = [(k, j) for k in b.open if k != b.opened[self.id] for j, hs in enumerate(b.tasks[k].holders) if not self.avoid & set(hs)]
        return [(k, j) for k, j in ok if self.hit & set(b.tasks[k].holders[j])] or ok

    def choose(self, b, t):
        self.turn += 1
        cand = self.candidates(b) if self.channel is not None and self.turn % 2 else []
        if cand:
            k, j = cand[int(self.rng.integers(len(cand)))]
            p, r = b.tasks[k].task.clue(j)
            return ('share', (k, j, int((r + 1 + self.rng.integers(p - 1)) % p)))
        return RuleAgent.choose(self, b, t)

