    for rs in sequences(ix, m, 'seqrm16').values():
        nl, base = _nl(rs), seqIndex(rs, _nl(rs), range(3), nNull)
        rem.append(seqIndex(rs, nl, (3, 4), nNull) - base)
        ret.append(seqIndex(rs, nl, (5,), nNull) - base)
