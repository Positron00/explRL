def recovery(ix, m, nNull=200):
    """At 16 agents with the removal: the index on boards 4-5 (removed) and on board 6 (returned) minus boards 1-3's, and
    the take-up: the remaining agents' contests per turn on boards 4-5 minus on boards 1-3."""
