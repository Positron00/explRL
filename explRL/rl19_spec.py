def dolIndex(rs, nLiar, positions=range(6)):
    """The division of labour (Gorelick et al. 2004): the mutual information between agents and TASKS over the tasks'
    marginal entropy, I(agent; task) / H(task), from the agents' turns across the boards at `positions` (1 when an
    agent's identity fixes its task, 0 when every agent has the same mix)."""
    M = np.array(list(taskMix(rs, nLiar, positions).values()))
    if len(M) < 2 or M.sum() <= 0:
        return NAN
    p = M / M.sum()
    pa, pt = p.sum(1, keepdims=True), p.sum(0)
    nz = p > 0
    H = float(-(pt[pt > 0] * np.log(pt[pt > 0])).sum())
    return float((p[nz] * np.log(p[nz] / (pa * pt)[nz])).sum()) / H if H > 0 else NAN


