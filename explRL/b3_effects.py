def c1PilotMap(pilotRows, scale=None):
    """FR-C6: refit's pilot targets, [dict(cell, value, s)]: each pilot arm's `contamination` (64 agents, independent liars),
    arm-matched to the simulated cell 'c1:<level>:64', for trustOne; s = scale(boards) (b3_fit.pilotScale), None without it."""
    out = []
    for lv in sorted({r['level'] for r in pilotRows}):
        v = [float(r['contamination']) for r in pilotRows if r['level'] == lv and np.isfinite(float(r['contamination']))]
        out.append(dict(cell=f'c1:{lv}:64', measure='contamination', value=float(np.mean(v)), boards=len(v),
                        s=scale(len(v)) if scale else None))
    return out


