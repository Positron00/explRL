def retroSaved(root='.'):
    """{id: dict(study, unfitted, estimate, ci)}: the frozen unfitted sign and the Haiku estimate and interval of each retro
    item, read from the saved prediction and score files (a study whose files are absent is left out; NFR-1: read only)."""
