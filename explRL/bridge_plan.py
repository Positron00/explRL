def pilotCheck20(rows, plan=None):
    """FR-C2 on the pilot's rows (levels '<arm>|independent'): invalid replies under 5%, mirror posts above 0, relays above 0
    on each bridge board, a bridge's input tokens per call at most 2 x 780; then the projection of c1Grid at the pilot's cost
    per call by arm and costRule20 (always 'ask'). A missing column fails its check. -> dict(ok, reasons, values, ...)."""
    plan = plan or C1_PILOT_PLAN
    P, col = plan['pilot'], plan['pilot']['columns']
    f = lambda r, k: float(r[k]) if r.get(k) not in (None, '') else float('nan')
    by = {arm20(r): r for r in rows}
    calls = sum(f(r, 'calls') for r in rows) or 1.0
    bridged = [a for a in by if ARMS20[a].get('bridges')]
    vals = dict(invalid=sum(f(r, 'invalid') for r in rows) / calls, mirrorPosts=sum(f(r, col['mirror']) for r in rows),
                relays={a: f(by[a], col['relays']) for a in bridged}, bridgeTokens={a: f(by[a], col['bridgeTok']) for a in bridged})
    reasons = [m for m, bad in [
        (f"missing pilot boards {sorted(set(P['cells']) - set(by))}", set(P['cells']) - set(by)),
        (f"invalid {vals['invalid']:.3f} >= {P['maxInvalid']}", not vals['invalid'] < P['maxInvalid']),
        (f"no mirror posts ({vals['mirrorPosts']})", not vals['mirrorPosts'] > 0)] +
        [(f'no relays on {a} ({v})', not v > 0) for a, v in vals['relays'].items()] +
        [(f"{a}: bridge input tokens per call {v:.0f} > {P['maxBridgeTokens']}", not v <= P['maxBridgeTokens'])
         for a, v in vals['bridgeTokens'].items()] if bad]
    perCall = {a: f(r, 'cost') / f(r, 'calls') for a, r in by.items() if f(r, 'calls')}
    est = c1Estimate(c1Grid(), perCall) if perCall else dict(cost=float('nan'))
    return dict(ok=not reasons, reasons=reasons, values=vals, perCall=perCall, estimate=est, **costRule20(est['cost'], plan))
