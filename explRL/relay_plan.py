def pilotCheck23(rows, plan=None):
    """P23-9 on the pilot's rows (levels '<arm>|independent'): invalid replies under 5%; mirror posts above 0; on each bridge arm,
    relays per bridge turn at least 0.05 and a bridge's mean input tokens per call at most 1,560 (P23-9 stops above it); mirror
    posts on every board (a window board must show something); on each evidence arm, at least
    one relay confirmed on arrival. Then the projection of c1bGrid at the pilot's cost per call by arm and costRule20 (always
    'ask'). A missing column fails its check. -> dict(ok, reasons, values, perCall, estimate, verdict, projected, ...)."""
    plan = plan or C1B_PILOT_PLAN
    P, col = plan['pilot'], plan['pilot']['columns']
    f = lambda r, k: float(r[k]) if r.get(k) not in (None, '') else float('nan')
    by = {arm23(r): r for r in rows}
    calls = sum(f(r, 'calls') for r in rows) or 1.0
    br, ev = [a for a in P['bridgeArms'] if a in by], [a for a in P['evidenceArms'] if a in by]
    vals = dict(invalid=sum(f(r, 'invalid') for r in rows) / calls, mirrorPosts=sum(f(r, col['mirror']) for r in rows),
                relaysPerBridgeTurn={a: f(by[a], col['relays']) for a in br}, bridgeTokens={a: f(by[a], col['bridgeTok']) for a in br},
                confirmedOnArrival={a: round(f(by[a], col['arrival']) * f(by[a], col['nRelays']), 6) for a in ev})   # 1/49 * 49 < 1
    reasons = [m for m, bad in [
        (f"missing pilot boards {sorted(set(P['cells']) - set(by))}", set(P['cells']) - set(by)),
        (f"invalid {vals['invalid']:.3f} >= {P['maxInvalid']}", not vals['invalid'] < P['maxInvalid']),
        (f"no mirror posts ({vals['mirrorPosts']})", not vals['mirrorPosts'] >= P['minMirrorPosts'])] +
        [(f'{a}: no mirror posts', not f(r, col['mirror']) >= P['minMirrorPosts']) for a, r in by.items()] +
        [(f"{a}: relays per bridge turn {v:.3f} < {P['minRelaysPerBridgeTurn']}", not v >= P['minRelaysPerBridgeTurn'])
         for a, v in vals['relaysPerBridgeTurn'].items()] +
        [(f"{a}: bridge input tokens per call {v:.0f} > {P['maxBridgeTokens']}", not v <= P['maxBridgeTokens'])
         for a, v in vals['bridgeTokens'].items()] +
        [(f'{a}: no relay confirmed on arrival ({v})', not v >= P['minArrivalConfirmed']) for a, v in vals['confirmedOnArrival'].items()] if bad]
    perCall = {a: f(r, 'cost') / f(r, 'calls') for a, r in by.items() if f(r, 'calls')}
    est = c1Estimate(c1bGrid(), perCall) if perCall else dict(cost=float('nan'))
    rule = costRule20(est['cost'], dict(costRule=plan['costRule']))
    return dict(ok=not reasons, reasons=reasons, values=vals, perCall=perCall, estimate=est, **rule)
