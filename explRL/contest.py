from dataclasses import dataclass, field

BONUS = 0.5                                   # the evaluation's wrong-answer cost: a prevented wrong answer's price
SLOTS = ('guards', 'all')


def preventionBonus(lag, H):
    "0.5 * 2 ** (-lag / H): the bonus per watcher of a contest made `lag` turns after the lie it answers."
    return BONUS * 2 ** (-float(lag) / float(H))


@dataclass
class Contest:
    t_c: float                                # time of the contest
    who: int                                  # the contester
    k: int                                    # the slot: subtask k, clue j
    j: int
    t_l: float                                # first post of the lie it answers
    lie: int                                  # that lie's residue
    liar: int                                 # its first poster
    watchers: dict = field(default_factory=dict)   # {agent: time of its correct solve of k, or None}


class ContestLog:
    """Contests on one board, built from the shares and what each agent was shown, as the game runs. A share by an honest
    agent of a clue's true value while the slot (k, j) shows a lie (a false value first posted by a liar) is a contest; its
    watchers are the honest agents, other than the contester and not holding clue j, that were shown a lie of the slot before
    any true value of it and before the contest. A watcher's later correct solve of k pays the contester, once per (contest,
    watcher), when the contester is in `contestSlots`."""
    def __init__(self, board, liarSlots, contestSlots, halfLife=4.0):
        self.board, self.liars, self.slots, self.H = board, frozenset(liarSlots), frozenset(contestSlots), float(halfLife)
        self.first, self.seenTrue, self.sawLie = {}, set(), {}   # {(k, j): {r: (poster, t)}}; {(i, k, j)}; {(k, j): {i: t}}
        self.contests, self.paid = [], []                          # paid: (t, contester, watcher, k, j, bonus)

    def _true(self, k, j):
        return self.board.tasks[k].task.clue(j)[1]

    def lies(self, k, j):
        "[(t, r, liar)]: the slot's false values first posted by a liar, oldest first."
        tr = self._true(k, j)
        return sorted((t, r, a) for r, (a, t) in self.first.get((k, j), {}).items() if a in self.liars and r != tr)

    def shownOn(self, visible):
        "{(k, j): residues}: the posted values an agent seeing the subtasks `visible` is shown."
        vis = set(visible)
        return {(k, j): set(v) for (k, j), v in self.first.items() if k in vis}

    def onShown(self, t, i, shown):
        "Agent i was shown `shown` ({(k, j): residues}) at t: note true values seen, and lies seen before any true value."
        if i in self.liars:
            return
        for (k, j), rs in shown.items():
            if (i, k, j) in self.seenTrue:
                continue
            if self._true(k, j) in rs:
                self.seenTrue.add((i, k, j))
            elif i not in self.board.tasks[k].holders[j] and any(r in rs for _, r, _ in self.lies(k, j)):
                self.sawLie.setdefault((k, j), {}).setdefault(i, float(t))

    def onShare(self, t, i, k, j, r, true):
        "Agent i posts residue r (true or not) for clue (k, j) at t; a contest is judged at this moment, before the post counts."
        lies = self.lies(k, j)
        if true and lies and i not in self.liars:
            w = {a: None for a in self.sawLie.get((k, j), {}) if a != i and (a, k, j) not in self.seenTrue}
            self.contests.append(Contest(float(t), i, k, j, lies[0][0], lies[0][1], lies[0][2], w))
        self.first.setdefault((k, j), {}).setdefault(int(r), (i, float(t)))
        if true:                                  # a poster of the true value knows it: no later contest's watcher
            self.seenTrue.add((i, k, j))

    def onSolve(self, t, i, k):
        "A correct solve of k by i at t, strictly after the contest (t > t_c) -> [(contester, bonus)] for the contests it qualifies for, contesters in contestSlots."
        out = []
        for c in self.contests:
            if c.k == k and i in c.watchers and c.watchers[i] is None and t > c.t_c:
                c.watchers[i] = float(t)
                if c.who in self.slots:
                    out.append((c.who, self.bonus(c)))
                    self.paid.append((float(t), c.who, i, k, c.j, out[-1][1]))
        return out

    def bonus(self, c, H=None):
        return preventionBonus(c.t_c - c.t_l, self.H if H is None else H)

    def earned(self, n):
        "Bonus per agent (length n) paid so far."
        out = [0.0] * n
        for _, a, _, _, _, x in self.paid:
            out[a] += x
        return out


def contestOptions(world, N, nLiar):
    "ClueBoardEnv's `contest` options from a world: liars in the first nLiar slots; contestSlots 'guards' or 'all'; halfLife."
    s, g = world.get('contestSlots'), int(world.get('guards', 0))
    if s not in SLOTS:
        raise ValueError(f"scheme 'contest' needs contestSlots in {SLOTS}, got {s!r}")
    slots = range(nLiar, nLiar + g) if s == 'guards' else range(nLiar, N)
    return dict(liarSlots=range(nLiar), contestSlots=slots, halfLife=float(world.get('halfLife', 4.0)))

