def boardType(N, nLiar, life):
    "The key of a board type in `warmAnswers`: (team size, liar count, subtask lifetime)."
    return int(N), int(nLiar), int(life)


def _table(warmAnswers):
    items = warmAnswers.items() if isinstance(warmAnswers, dict) else warmAnswers
    return {tuple(int(x) for x in k): float(v) for k, v in items}


def sharePenalty(answers, boardType, warmAnswers, amount):
    "amount for every honest slot if answers < warmAnswers[boardType] / 3, else 0 (a board type missing from the table fails)."
    ref = _table(warmAnswers)[tuple(int(x) for x in boardType)]
    return float(amount) if answers < ref / 3 else 0.0


def honestAnswers(board, nLiar):
    "Submissions by the honest slots (every slot from nLiar on), whatever their result."
    return sum(1 for s in board.submits if s[1] >= nLiar)


def applySharePenalty(board, nLiar, warmAnswers, amount):
    "At the board's end: the penalty, if due, taken from every honest slot's pending reward (its last reward). -> the penalty."
    p = sharePenalty(honestAnswers(board, nLiar), boardType(board.nAgents, nLiar, board.life), warmAnswers, amount)
    board.endPenalty(range(nLiar, board.nAgents), p)
    return p

