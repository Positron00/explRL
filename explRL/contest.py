class Records:
    """Each agent's own payoffs from solves and contests over the earlier boards of a sequence of `length` boards (arm 4).
    `addBoard` adds a finished board and starts the next; after `length` boards the records reset (a new sequence)."""
    KINDS = ('answers', 'contests')

    def __init__(self, N, length=6):
        self.N, self.length = int(N), int(length)
        self.reset()

    def reset(self):
        self.boards, self.cur = [], self._fresh()

    def _fresh(self):
        return [dict.fromkeys(self.KINDS, 0.0) for _ in range(self.N)]

    def add(self, i, kind, payoff):
        self.cur[i][kind] += float(payoff)

    def endBoard(self):
        self.boards.append(self.cur)
        self.cur = self._fresh()
        if len(self.boards) >= self.length:
            self.reset()

    def addBoard(self, board, slots):
        "A finished board: per slot, the value of its own answers (solved values minus wrong-answer costs) and its contest bonuses."
        net, log = board.netByAgent(), getattr(board, 'contestLog', None)
        won = log.earned(board.nAgents) if log is not None else [0.0] * board.nAgents
        for i in slots:
            self.add(i, 'answers', net[i])
            self.add(i, 'contests', won[i])
        self.endBoard()

    def line(self, i):
        "The prompt line for agent i: its own record only."
        if not self.boards:
            return 'Your record: this is the first board of a sequence of %d.' % self.length
        parts = [f"board {n + 1}: your answers earned {b[i]['answers']:.2f}, your contests earned {b[i]['contests']:.2f}"
                 for n, b in enumerate(self.boards)]
        return f'Your record on the earlier boards of this sequence of {self.length}: ' + '; '.join(parts) + '.'
