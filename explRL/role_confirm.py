def c1cSummary(rows, plan=C1C_PLAN, nboot=None):
    """The gate with part (i)'s robustness on welfareHonest, each arm's measures (mean and bootstrap interval over its boards),
    and the hand-recorded calls scored against the verdicts. ValueError unless all 16 planned cells are present."""
