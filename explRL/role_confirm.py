def gateC1c(rows, plan=C1C_PLAN, nboot=2000, metric='honestPooled'):
    """Gate C1c over the 8 paired boards. Part (i): arm - base in `metric`, one-sided exact sign-flip, passes at p < alpha with a
    positive estimate. Part (ii): arm - base in contamination, holds when the 95th percentile of the paired bootstrap means is
    below the margin. Verdict: passes (both) or fails, with what it decides for A1."""
    G, s8 = plan['gate'], set(plan['seeds'])
    i = _test(_d(rows, G['arm'], G['base'], metric, seeds=s8), nboot)
    i['passes'] = bool(i['p'] < G['alpha'] and i['estimate'] > 0)
    c = _d(rows, G['arm'], G['base'], G['safety'], seeds=s8)
    ii = dict(_test(c, nboot, 'less'), upper=upperBound(c, nboot, G['quantile']), margin=G['margin'])
    ii['holds'] = bool(ii['upper'] < G['margin'])
    v = 'passes' if i['passes'] and ii['holds'] else 'fails'
    return dict(metric=metric, i=i, ii=ii, passes=v == 'passes', verdict=v, decides=G['decides'][v])


