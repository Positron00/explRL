    arms = {a: {m: bootSeeds({k: v for k, v in cellVals(rows, a, 'independent', m, [N20]).items() if v == v}, nboot=nboot)
                for m in C1C_MEASURES} for a in plan['arms']}
    got = dict(H24_1='passes' if gate['i']['passes'] else 'fails', H24_2='holds' if gate['ii']['holds'] else 'fails', gate=gate['verdict'])
    calls = {k: {h: dict(call=v['call'] if isinstance(v, dict) else v, observed=got[h],
                         right=(v['call'] if isinstance(v, dict) else v) == got[h]) for h, v in plan['calls'][k].items()}
             for k in ('pilotOnly', 'everyDesignHelps')}
    cost = sum(float(r.get('cost', 0) or 0) for r in rows)
    return dict(gate=gate, arms=arms, calls=calls, boards=len(rows), cost=cost,
                invalid=sum(float(r['invalid']) for r in rows) / (sum(float(r['calls']) for r in rows) or 1))


