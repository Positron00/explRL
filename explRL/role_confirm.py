    key = lambda r: (r['level'], int(float(r['seed'])))
    rows = [r for r in rows if int(float(r['N'])) == N20 and key(r) in want]
    if miss := sorted(want - {key(r) for r in rows}):
        raise ValueError(f'{len(miss)} planned C1c cells missing, e.g. {miss[:4]}')
    gate, rob = gateC1c(rows, plan, nboot), gateC1c(rows, plan, nboot, 'welfareHonest')
