def waitRate(ix, m, tests):
    "The waiting rate over the tests' boards: non-guard answers that waited for a second sender / those using a posted value."
    return ratio(ix, m, tests, 'waitAnswers', 'usedAnswers')


def waitCurve(ix, m):
    "{liars: waiting rate} over both lifetimes."
    return {n: waitRate(ix, m, [f'gL{n}T{L}' for L in LIFETIMES]) for n in GATE_LIARS}


def waitGrid(ix, m):
    "{'L<liars>T<lifetime>': waiting rate} (string keys: the summary is JSON)."
    return {f'L{n}T{L}': waitRate(ix, m, [f'gL{n}T{L}']) for n in GATE_LIARS for L in LIFETIMES}


def waitSlope(curve):
    "Least-squares slope of the waiting rate over liar count (NaN with fewer than two finite points)."
    x = [n for n, v in sorted(curve.items()) if np.isfinite(v)]
    return float(np.polyfit(x, [curve[n] for n in x], 1)[0]) if len(x) > 1 else NAN


def lifeGap(ix, m):
    "H19-6: the waiting rate at lifetime 15 minus at 30, over every liar count."
    return waitRate(ix, m, [f'gL{n}T15' for n in GATE_LIARS]) - waitRate(ix, m, [f'gL{n}T30' for n in GATE_LIARS])


def regret(ix, m, warm='warm'):
    """Mean over the gate grid's liar counts and lifetimes of the honest welfare under the warm start's best fixed enforceK
    at that liar count and lifetime (chosen separately for each), minus the model's on the same boards."""
    best = {t: max(mean(ix, warm, f'k{K}' + t[1:], 'welfareHonest') for K in K19) for t in GATE}
    return float(np.mean([best[t] - mean(ix, m, t, 'welfareHonest') for t in GATE]))


