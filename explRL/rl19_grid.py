def evalAdapter19(runDir, haltAnswers=BASE19['haltAnswers'], haltRun=3, haltKLRun=FIX18['haltKLRun']):
    """The adapter a Phase 19 run is evaluated with: `final`, or for a halted run the last checkpoint whose policy produced no
    step of the halting streak (None, the warm start, if that is step 0). Step m's rollouts (answers, invalid replies) and its
    logged KL (one pass: measured before the update) come from ckpt-(m-1), the policy before step m's update, so a streak of
    n steps ending at step h began with ckpt-(h-n): the adapter is ckpt-(h-n-1). A jump halt at loop step s (halted.json
    'step' = s, two roll-backs in a row): ckpt-(s-1) also jumped when replayed, so the adapter is ckpt-(s-2).
    Unlike rl18_grid.evalAdapter (ckpt-(h-n)), which Phase 18 kept; none of its runs halted."""
    from pathlib import Path
    d = Path(runDir)
    if not (d / 'halted.json').exists():
        return str(d / 'final')
    h = json.loads((d / 'halted.json').read_text())
    why = h['reason']
    n = 1 if why.startswith('jump') else haltAnswers if 'answers' in why else haltRun if 'invalid' in why else haltKLRun
    k = h['step'] - n - 1
    return str(d / f'ckpt-{k:04d}') if k > 0 else None
