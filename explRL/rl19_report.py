def figRL19(out, S):
    "rl19.png: damage won back at 4 liars per arm (runs and mean), waiting rate against liars per arm, arm 4's specialization by team size."
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(1, 3, figsize=(12, 3.6))
    col = dict(a19credit='#7f7f7f', a19contest='#1f6391', a19fixed='#c0392b', a19open='#2e8b57')
    for k, a in enumerate(S['arms']):
        v = [S['perRun'][m]['damage'][4] for m in runNames19(a) if m in S['perRun']]
        ax[0].plot([k] * len(v), v, 'o', color=col[a], alpha=0.5)
        ax[0].plot([k - 0.25, k + 0.25], [S['arms'][a]['damage'][4]] * 2, '-', color=col[a], lw=2)
        ax[1].plot(list(S['arms'][a]['waitCurve']), list(S['arms'][a]['waitCurve'].values()), '-o', color=col[a], label=ARM_LABEL[a])
    ax[0].set(xticks=range(len(S['arms'])), xticklabels=[ARM_LABEL[a].split(' ')[0] for a in S['arms']], xlabel='arm', ylabel='damage won back (4 of 16 liars)')
    ax[1].set(xlabel='liars of 16', ylabel='waiting rate')
    ax[1].legend(fontsize=7)
    for m, v in S['spec'].items():
        ax[2].plot([8, 16, 32], [v['spec'][N] for N in (8, 16, 32)], 'k-o' if m == 'warm' else '-', color=None if m == 'warm' else col['a19open'], lw=2 if m == 'warm' else 0.8)
    ax[2].set(xscale='log', xticks=[8, 16, 32], xticklabels=['8', '16', '32'], xlabel='team size', ylabel='specialization (arm 4; black: warm)')
    fig.tight_layout()
    fig.savefig(f'{out}/rl19.png', dpi=150, metadata={'Software': None})
    plt.close(fig)
