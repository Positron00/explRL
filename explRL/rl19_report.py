ARM_LABEL = dict(a19credit='1 credit', a19contest='2 contest, varied', a19fixed='3 contest, fixed 4', a19open='4 open')


def runNames19(arm, runs=RUNS19):
    return [f'{a}_s{s}' for a, s in runs if a == arm]


def _m(v):
    v = [x for x in v if np.isfinite(x)]
    return float(np.mean(v)) if v else NAN


def haltCauses(halts):
    "{cause: runs} from {run: halted.json reason or None}: invalid replies, KL, answers, jump, or none."
    out = {}
    for run, why in sorted((halts or {}).items()):
        c = 'none' if not why else next((k for k in ('answers', 'jump', 'KL', 'invalid') if k in why), 'other')
        out.setdefault(c, []).append(run)
    return out


def rl19Summaries(rows, plan=RL19_PLAN, runs=RUNS19, nboot=2000, warm='warm', seeds=10, halts=None, nNull=200):
    """RL19_PLAN's analysis over the evaluation rows (contestSuite levels; sequence rows for arm 4 and the warm start).
    -> hyp (H19-1 to H19-6), gate (Gate A1), kill, best, arms (per-arm means), perRun, spec, halts."""
    ix, A = index(rows), {a: runNames19(a, runs) for a in ARMS19}
    names, alpha = [n for v in A.values() for n in v], plan['alpha']
    coverage(ix, names, warm, seeds, sequences=A['a19open'])
    M = {m: runMeasures(ix, m, warm) for m in names + [warm]}
    col = lambda arm, f: [f(M[m]) for m in A[arm]]
    d4, sl = (lambda x: x['damage'][4]), (lambda x: x['waitSlope'])
    hyp = {h: dict(permTest(col(a, f), col(b, f)), n=[len(A[a]), len(A[b])], arms=[a, b])
           for h, a, b, f in (('H19_1', 'a19contest', 'a19credit', d4), ('H19_2', 'a19contest', 'a19fixed', sl))}
    prim = plan['families']['primary']
    for h, q in zip(prim, holm([hyp[h]['p'] for h in prim])):
        hyp[h].update(estimate=hyp[h]['diff'], pHolm=float(q), supported=bool(q < alpha and hyp[h]['diff'] > 0))
    w0 = float(np.mean([float(r['honestPooled']) for t in ('gL0T15', 'gL0T30') for r in ix.get(f'{warm}|plain{t}', [])]))
    b0 = {m: {(r['seed'], t): float(r['honestPooled']) for t in ('gL0T15', 'gL0T30') for r in ix.get(f'{m}|{t}', [])} for m in A['a19contest']}
    est = _m(col('a19contest', lambda x: x['cost0']))       # cost without liars: the warm start without guards minus arm 2
    hyp['H19_3'] = dict(estimate=est, margin=0.05, holds=bool(est <= 0.05), ci=hierBoot({'a': b0}, lambda d: w0 - float(d['a'].mean()), nboot),
                        raw=_m(col('a19contest', lambda x: x['raw0'])), constraint=True)
    spec = {m: specMeasures(ix, m, nNull) for m in A['a19open'] + [warm]} if A['a19open'] else {}
    if spec:
        d = [spec[m]['spec'][16] - spec[warm]['spec'][16] for m in A['a19open']]
        sf, slopes = signFlip(d), [spec[m]['specSlope'] for m in A['a19open']]
        hyp['H19_4'] = dict(estimate=sf['mean'], p=sf['p'], n=len(d), supported=bool(sf['p'] < alpha and sf['mean'] > 0),
                            slope=dict(estimate=_m(slopes), ci=_boot(slopes, nboot), warm=spec[warm]['specSlope']),
                            persistence=dict(estimate=_m([spec[m]['persistence'] for m in A['a19open']]), warm=spec[warm]['persistence']),
                            recovery={k: _m([spec[m]['recovery'][k] for m in A['a19open']]) for k in ('removed', 'returned', 'takeUp')},
                            killCriterion=True)
    drift = {}
    for a, ms in A.items():
        x = [M[m]['misreport'] - M[warm]['misreport'] for m in ms]
        drift[a] = dict(estimate=_m(x), ci=_boot(x, nboot), collapse=_m([M[m]['collapse'] for m in ms]))
    hyp['H19_5'] = dict(drift=drift, collapsed=[a for a, v in drift.items() if v['collapse'] > 0.5], secondary=True)
    gap = col('a19contest', lambda x: x['lifeGap'])
    sf = signFlip([-g for g in gap])
    hyp['H19_6'] = dict(estimate=_m(gap), ci=_boot(gap, nboot), p=sf['p'], secondary=True)
    gate = bool(all(hyp[h]['supported'] for h in prim) and hyp['H19_3']['holds'])
    arms = {a: {k: _m(col(a, (lambda x, k=k: x[k]))) for k in ('waitSlope', 'regret', 'contestsPerLie', 'contestsPerGuardLie',
            'timeToContest', 'guardedLies', 'misreport', 'cost0', 'raw0', 'gullibility', 'suppression', 'errorCorr', 'collaboration',
            'welfare', 'welfarePerKTok', 'lifeGap', 'collapse')} for a, ms in A.items() if ms}
    for a in arms:
        arms[a].update(damage={n: _m(col(a, lambda x, n=n: x['damage'][n])) for n in (2, 4, 6, 8)},
                       waitCurve={n: _m(col(a, lambda x, n=n: x['waitCurve'][n])) for n in (0, 2, 4, 6, 8)},
                       waitGrid={c: _m(col(a, lambda x, c=c: x['waitGrid'][c])) for c in M[warm]['waitGrid']},
                       held={k: _m(col(a, lambda x, k=k: x['held'][k])) for k in ('n8', 'n32', 'error', 'collude')})
    best = 'a19contest' if gate else max(arms, key=lambda a: arms[a]['damage'][4] if np.isfinite(arms[a]['damage'][4]) else -np.inf)
    return dict(hyp=hyp, gate=gate, kill=bool(not gate and not hyp.get('H19_4', {}).get('supported', False)), best=best,
                arms=arms, perRun=M, spec=spec, halts=haltCauses(halts))

