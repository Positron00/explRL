def retroFold(fold, knob, theta0, tau, thetas, pilotRows, priorRows, rows, saved, workers=8, seeds=SIM_SEEDS):
    """One fold for one candidate knob: refit θ0 on the fold's pilot over `thetas` (the candidate's grid), then the five lines on
    the fold's items and their scores against the saved Haiku intervals."""
    effs = [e for e in RETRO_EFFECTS if e.id in RETRO_STUDIES[fold]['ids']]
    cells, tg, params = pilotTargets(fold, pilotRows, rows)
    params = tuple(knob if p is None else p for p in params)
    fixed = [k for k in ('trustOne', knob) if k not in params]
    cand = [th for th in thetas if all(th.get(k, 0.0) == theta0.get(k, 0.0) for k in fixed)]
    thp = refit(theta0, tau, tg, gridSim(cells, cand, workers, seeds), params) if tg and params else dict(theta0)
    est = p14Estimate if fold == 'P14' else estimate
    th = dict(fitted=thp, priorOnly=theta0, unfitted={})
    lines = {k: forecastSim(effs, retroCellFn, t, seeds, est) for k, t in th.items()}
    if fold != 'P14':                                 # team size is not a design: no pilot-only or every-design-helps (P22-11)
        lines.update(pilotOnly=forecastPilot(effs, pilotRows, priorRows, est), naive=forecastNaive(effs))
    items = {e.id: dict(saved[e.id], lines={k: v[e.id]['sign'] for k, v in lines.items() if e.id in v},
                        calls={k: call(v[e.id]['sign'], saved[e.id]['ci']) for k, v in lines.items() if e.id in v})
             for e in effs if e.id in saved}
    for i in items.values():
        i['unfittedMatches'] = i['lines']['unfitted'] == i['unfitted']
    return dict(fold=fold, knob=knob, theta=dict(th, fitted=thp), pilot=tg, params=list(params), items=items)


def _counts(items, lines=('fitted', 'priorOnly', 'unfitted', 'pilotOnly', 'naive')):
    return {k: {o: sum(i['calls'].get(k) == o for i in items) for o in ('right', 'wrong', 'no call')} for k in lines}


def retrospective(fitRes, workers=8, seeds=SIM_SEEDS, root=None, thetas=None, folds=('S1', 'S4', 'S4b', 'P14'), knobs=CANDIDATES):
    """FR-D2: every fold for every candidate: θ0 = the candidate's held-out fit (the winner's fine-grid fit), τ its bootTau; the
    winner refits on its fine grid, the others on the coarse grid (`thetas(knob)` overrides). Counts on the 11 conclusive calls
    (H22-2: fitted right > the unfitted 9), P14 apart, and whether the unfitted line reproduces the frozen signs."""
    from explRL.b3_cells import claudeRows
    from explRL.bench_grid import readCSV
    from explRL.train import demo_artifact_dir
    R = demo_artifact_dir(None, 'multiagent') if root is None else root
    rows, saved, out = claudeRows(R), retroSaved(R.parents[1]), {}
    for k in knobs:
        g = thetas(k) if thetas else grid(('trustOne', k), 'fine' if k == fitRes['knob'] else None)
        out[k] = {}
        for f in folds:
            held = fitRes['heldOut']['fine' if k == fitRes['knob'] else 'coarse']
            th0 = (held[f] if k == fitRes['knob'] else held[k][f])['theta']
            prior = [r for d in RETRO_PRIOR[f] for r in readCSV(R / d / 'runs.csv') if r.get('runner', 'llm') == 'llm']
            out[k][f] = retroFold(f, k, th0, fitRes['tauBy'][k], g, readCSV(R / RETRO_PILOTS[f] / 'runs.csv'), prior, rows,
                                  saved, workers, seeds)
    summary = {}
    for k in out:
        concl = [i for f in CONCLUSIVE if f in out[k] for i in out[k][f]['items'].values() if i['calls']['unfitted'] != 'no call']
        summary[k] = dict(conclusive=len(concl), counts=_counts(concl), H22_2=_counts(concl)['fitted']['right'] > 9,
                          P14=_counts(out[k]['P14']['items'].values(), ('fitted', 'priorOnly', 'unfitted')) if 'P14' in out[k] else None,
                          unfittedMismatch=[i for f in out[k] for i, v in out[k][f]['items'].items() if not v['unfittedMatches']])
    return dict(knob=fitRes['knob'], folds=out, summary=summary,
                caveat='in-sample: the behaviours were named after these misses, and the knob was chosen on the same folds (P22-18)')
