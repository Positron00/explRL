def _cell(arm, fault, N, tag='retro'):
    return dict(id=f'{tag}:{arm}|{fault}:{N}', kind='p14' if arm == 'baseline' else 'colony', arm=arm, fault=fault, N=int(N),
                target='pooledShare' if fault == 'clean' else 'contamination')


def retroCellFn(arm, fault, N, seed, theta):
    "One numpy board of a retrospective item's cell (Phase 14's plain board for arm 'baseline'), with world['b3'] = θ."
    return simRow(_cell(arm, fault, N), seed, theta)


def pilotTargets(fold, pilotRows, rows):
    """A study's pilot as refit targets: clean boards on pooledShare, liar boards on contamination (rows without the measure are
    skipped); s from the Claude fit cells outside the fold (pilotScale, one board each) -> ([cell], [target], refit params)."""
    keep = [c for c in FIT_CELLS if c['id'] not in FOLDS[fold]]
    cells, tg = [], []
    for r in pilotRows:
        arm, fault = (r['level'].split('|') + ['clean'])[:2]
        c = _cell(arm, fault, float(r['N']), 'pilot')
        if r.get(c['target']) not in (None, '') and np.isfinite(float(r[c['target']])):
            cells.append(c)
            tg.append(dict(cell=c['id'], measure=c['target'], value=float(r[c['target']]), s=pilotScale(rows, c['target'], 1, keep)))
    params = tuple(p for p, m in (('trustOne', 'contamination'), (None, 'pooledShare')) if any(t['measure'] == m for t in tg))
    return cells, tg, params

