class RoleBridge(RuleAgent):
    "Mixin over RuleBridge's classes: on a dedicated bridge's slot, relay an untied confirmed mirror leader the board lacks, else wait."
    def choose(self, b, t):
        if self.id in getattr(b, 'roleBridges', ()):
            return (self._roleRelay(b) or self._shareable(b, None, t, sorted(b.open, key=lambda k: (b.tasks[k].expire, k)))
                    or ('wait', None))
        return super().choose(b, t)

    def _roleRelay(self, b):
        p, q = b.bridgeOf(self.id), getattr(self, 'q', Q)
        if p is None or self.channel is None:
            return None
        tal = tally(self.channel, b)
        for k in b.open:
            if b.coupled.get(k) != p:
                continue
            mt = b.mirrorTally(k).get(k, {}).get(1, [])
            if not mt or len(mt[0][1]) < q or len(mt) > 1 and len(mt[1][1]) == len(mt[0][1]):
                continue
            lead, r = leading(tal, k, 1), int(mt[0][0])
            if (lead is None or lead[0] != r) and not any(x[1] == self.id and x[2] == k and x[4] == r for x in b.relayLog):
                return ('share', (k, 1, r))
        return None


@lru_cache(None)
def _roled(cls):
    return type('Role' + cls.__name__, (RoleBridge, cls), {})


def relayMembers(world, members):
    """bridgeMembers' hook: with bridgeRole, every RuleBridge member (honest rule agents) gains RoleBridge (class Role<class>),
    InSquad wrappers kept. Without it, or for Claude members, nothing changes. Returns `members`."""
    if not world.get('bridgeRole'):
        return members
    for m in members:
        x = m.m if isinstance(m, InSquad) else m
        if isinstance(x, RuleBridge) and not isinstance(x, RoleBridge):
            x.__class__ = _roled(type(x))
    return members
