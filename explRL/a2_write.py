def figA2(out, S):
    "a2.png: guarding of the success (solid) and failure (dashed) guards by board and arm; P2's suppressedHeld by size and prompt."
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    fig, (a, b) = plt.subplots(1, 2, figsize=(11, 3.8), gridspec_kw=dict(width_ratios=[3, 2]))
    col = dict(none='#7f7f7f', shared='#1f6391', own='#c0392b')
    for arm, v in S.get('arms', {}).items():
        bs = sorted(v['guarding'])
        a.plot(bs, [v['guarding'][x][0] for x in bs], '-o', color=col.get(arm), ms=4, label=f'{arm}: success guards')
        a.plot(bs, [v['guarding'][x][1] for x in bs], '--', color=col.get(arm), label=f'{arm}: failure guards')
    a.axvline(2.5, color='#555555', lw=0.8, ls=':')
    a.set(xlabel='board (records from board 3)', ylabel='guarding (held-clue posts / turns)',
          title=f"Gate A2 {'passes' if S['gate']['passes'] else 'fails' if S['gate']['read'] else 'not read'}")
    a.legend(fontsize=6, frameon=False, ncol=2)
    for i, N in enumerate(P2_N):
        v = S['p2'][N]['suppressedHeld']
        b.bar([3 * i, 3 * i + 1], [v['orig'], v['drop']], 0.8, color=['#7f7f7f', '#2e8b57'])
    b.set_xticks([0, 1, 3, 4], ['N 8 orig', 'N 8 drop', 'N 32 orig', 'N 32 drop'], fontsize=8)
    b.set(ylabel='liar-first posts left uncorrected', title='Re-sharing sentence (H21-3)', ylim=(0, 1))
    for ax in (a, b):
        ax.spines[['top', 'right']].set_visible(False)
    fig.tight_layout()
    fig.savefig(f'{out}/a2.png', dpi=150, metadata={'Software': None})
    plt.close(fig)
