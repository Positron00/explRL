def _slots(nLiar, N=N20):
    "Per-slot JSON columns (contestColumns' layout): honest even slots share more than odd ones, guards contest."
    j = lambda f: json.dumps([0 if i < nLiar else f(i) for i in range(N)])
    return dict(agentTurns=json.dumps([40] * N), agentShares=j(lambda i: 20 if i % 2 == 0 else 5),
                agentContests=j(lambda i: 2 if nLiar <= i < nLiar + 16 else 0), agentSubmits=j(lambda i: 5), agentOpens=j(lambda i: 5))


def syntheticRows20(lead=0.171, cost=0.10, back=0.07, second=0.01, guard=0.005, clean=(0.03, 0.01), falseRelay=(0.3, 0.1),
                    contamination=(0.08, 0.03), noise=0.02, seed=0, plan=C1_PLAN):
    """Rows of every planned C1 cell (N 64; planned20) with known effects in honestPooled (welfareHonest 1.3 times it, welfare
    equal): colonyGuards 0.07; squads = colonyGuards + lead; coupled = squads - cost; bridge1 = coupled + back; bridge2 =
    bridge1 + second; bridgeGuard = bridge1 + guard. Clean boards: squads 0.40, coupled 0.40 - clean[0], bridge1 0.40 - clean[1].
    False-relay share and cross-squad contamination: bridge1 and bridge2 at [0], bridgeGuard at [1], coupled no relays (NaN)
    and no contamination (0). One noise draw per seed is shared by every arm, so paired differences are exact. The core
    measures' columns are the same on every board (gullibility 6 / honestTurns, suppression 2 / 4, and so on)."""
    rng, rows = np.random.default_rng(seed), []
    e = {s: rng.normal(0, noise) for s in sorted({s for _, s in planned20(plan)})}
    hp = dict(colonyGuards=0.07, squads=0.07 + lead)
    hp.update(coupled=hp['squads'] - cost, bridge1=hp['squads'] - cost + back)
    hp.update(bridge2=hp['bridge1'] + second, bridgeGuard=hp['bridge1'] + guard)
    hc = dict(squads=0.40, coupled=0.40 - clean[0], bridge1=0.40 - clean[1])
    pick = lambda a, v: v[1] if a == 'bridgeGuard' else 0.0 if a == 'coupled' else v[0]
    for lv, s in sorted(planned20(plan)):
        a, f = lv.split('|')
        nl, h = (0, hc[a]) if f == 'clean' else (16, hp[a])
        x, cp = h + e[s], ARMS20[a].get('couple')
        rows.append(dict(level=lv, seed=s, N=N20, nLiar=nl, tEnd=40.0, honestPooled=x, welfareHonest=1.3 * x, welfare=x,
                         falseRelayShare=pick(a, falseRelay) if ARMS20[a].get('bridges') else NAN,
                         crossContamination=pick(a, contamination) if cp else NAN, bridgeRelays=40.0 if ARMS20[a].get('bridges') else 0.0,
                         mirrorPosts=200.0 if cp else 0.0, contamination=0.3, inTokPerCall=780.0, honestTurns=40.0 * (N20 - nl),
                         misinformedFirst=6.0 if nl else 0.0, liarFirst=4.0 if nl else 0.0, uncorrected=2.0 if nl else 0.0,
                         liarPosts=20.0 if nl else 0.0, contests=10.0 if nl else 0.0, guardLies=8.0 if nl else 0.0,
                         contestLags=json.dumps([1.0, 3.0] if nl else []), wrongHonest=6.0, sameWrong=2.0, sharePerHeld=0.5,
                         inputTokens=1.5e6, outputTokens=3e5, solved=30.0, **_slots(nl)))
    return rows


def syntheticPartB(gain4=0.05, gain1=0.006, loss=(0.04, 0.08), runSd=0.01, noise=0.02, seed=0, models=PARTB_MODELS):
    """Part b rows (levels '<model>|n32sq4', '|n32sq4liar', '|n32', '|n32liar', seeds 900-909) with known effects: every adapter
    gains gain4 over the warm start in squads of 4 and gain1 on one board, plus a run effect shared by both arms (so each run's
    difference is exactly gain4 - gain1); honest loss with liars loss[0] in squads of 4 and loss[1] on one board."""
    rng, rows = np.random.default_rng(seed), []
    e = {s: rng.normal(0, noise) for s in BIG_SEEDS}
    for m in models:
        u = 0.0 if m == 'warm' else rng.normal(0, runSd)
        for (c, l), g, ls, base in ((PARTB_TESTS['squads4'], gain4, loss[0], 0.32), (PARTB_TESTS['oneBoard'], gain1, loss[1], 0.30)):
            for s in BIG_SEEDS:
                w = base + e[s] + (0.0 if m == 'warm' else g + u)
                rows += [dict(level=f'{m}|{c}', seed=s, N=32, nLiar=0, welfare=w, welfareHonest=w),
                         dict(level=f'{m}|{l}', seed=s, N=32, nLiar=8, welfare=w - ls, welfareHonest=w - ls)]
    return rows
