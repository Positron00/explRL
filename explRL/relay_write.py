def figC1b(out, S):
    "c1b.png (FR-D4): per arm with liars, honest pooled share (left) and contamination with bridge1 + the margin (right)."
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    A, G = S['arms'], S['gate']
    fig, axes = plt.subplots(1, 2, figsize=(11, 3.8))
    for ax, m, title in ((axes[0], 'honestPooled', 'Effective: honest pooled share'), (axes[1], 'contamination', 'Safe: contamination')):
        for x, (arm, v) in enumerate(A.items()):
            e, lo, hi = v[m]
            if np.isfinite(e):
                ax.errorbar([x], [e], yerr=[[e - lo], [hi - e]], fmt='o', capsize=3, ms=7,
                            color='#1f6391' if arm in ('relayEvid', 'bridgeRole', 'bridgeFix', 'mirrorWindow') else '#555555')
        ax.set_xticks(range(len(A)), list(A), rotation=30, ha='right', fontsize=8)
        ax.set(ylabel=m, title=title)
        ax.spines[['top', 'right']].set_visible(False)
    ref = A['bridge1']['contamination'][0]
    axes[1].axhline(ref + G['ii']['margin'], color='#c0392b', lw=1, ls='--', label='bridge1 + 0.05: the bar of part (ii)')
    axes[1].legend(fontsize=7, frameon=False)
    fig.suptitle(f"64 agents with liars; Gate C1b {G['verdict']}", fontsize=10)
    fig.tight_layout()
    fig.savefig(f'{out}/c1b.png', dpi=150, metadata={'Software': None})
    plt.close(fig)

