def syntheticRows23(squads=0.24, cost=0.09, bridge1=0.01, ev=0.025, role=0.025, inter=0.0, window=0.08, safety=0.0, safetyNoise=0.0,
                    clean=0.40, noise=0.02, seed=0, plan=C1B_PLAN):
    """Rows of every planned C1b cell (N 64; planned23) with known effects. honestPooled (welfareHonest 1.3 times it): squads;
    coupled = squads - cost; bridge1 = coupled + bridge1; relayEvid = bridge1 + ev; bridgeRole = bridge1 + role; bridgeFix =
    bridge1 + ev + role + inter; mirrorWindow = coupled + window. Contamination 0.20 on the bridge arms, bridgeFix 0.20 + safety
    (+ a per-seed draw of sd safetyNoise), mirrorWindow 0.22, coupled 0.18, squads 0.15. One noise draw per seed is shared
    by every arm, so paired differences are exact. Clean boards: clean, minus 0.03 (coupled), 0.058 (bridge1), 0.02 (bridgeFix),
    0.01 (mirrorWindow). Relay columns: filterGain 0.2, arrivalConfirmed 0.6 on evidence arms (0.3 otherwise), truthConfirmable
    0.52, liarConfirmed 0.018; coupledContamination 0.05 (coupled), 0.06 elsewhere."""
    rng, rows = np.random.default_rng(seed), []
    want = sorted(planned23(plan))
    e = {s: rng.normal(0, noise) for s in sorted({s for _, s in want})}
    es = {s: rng.normal(0, safetyNoise) if safetyNoise else 0.0 for s in e}
    hp = dict(squads=squads, coupled=squads - cost)
    hp.update(bridge1=hp['coupled'] + bridge1, mirrorWindow=hp['coupled'] + window)
    hp.update(relayEvid=hp['bridge1'] + ev, bridgeRole=hp['bridge1'] + role, bridgeFix=hp['bridge1'] + ev + role + inter)
    hc = dict(squads=clean, coupled=clean - 0.03, bridge1=clean - 0.058, bridgeFix=clean - 0.02, mirrorWindow=clean - 0.01)
    con = dict(squads=0.15, coupled=0.18, mirrorWindow=0.22)
    for lv, s in want:
        a, f = lv.split('|')
        w, nl = ARMS23[a], 0 if f == 'clean' else 16
        x, br, cp = (hc[a] if nl == 0 else hp[a]) + e[s], w.get('bridges'), w.get('couple')
        c = con.get(a, 0.20) + (safety + es[s] if a == 'bridgeFix' else 0.0)
        rel = dict(filterGain=0.2 if br else NAN, arrivalConfirmed=(0.6 if w.get('evidence') else 0.3) if br else NAN,
                   reRelays=1.0 if br else NAN, roleBreaks=0.0 if w.get('bridgeRole') else NAN,
                   coupledContamination=(0.05 if a == 'coupled' else 0.06) if cp else NAN,
                   truthConfirmable=0.52 if cp else NAN, liarConfirmed=0.018 if cp else NAN)
        rows.append(dict(level=lv, seed=s, N=N20, nLiar=nl, tEnd=40.0, honestPooled=x, welfareHonest=1.3 * x, welfare=x,
                         contamination=c, falseRelayShare=0.3 if br else NAN, crossContamination=0.05 if cp else NAN,
                         bridgeRelays=30.0 if br else 0.0, relaysPerBridgeTurn=0.1 if br else NAN, mirrorPosts=200.0 if cp else 0.0,
                         inTokPerCall=800.0, honestTurns=40.0 * (N20 - nl), misinformedFirst=6.0 if nl else 0.0,
                         liarFirst=4.0 if nl else 0.0, uncorrected=2.0 if nl else 0.0, liarPosts=20.0 if nl else 0.0,
                         contests=10.0 if nl else 0.0, guardLies=8.0 if nl else 0.0, contestLags=json.dumps([1.0, 3.0] if nl else []),
                         wrongHonest=6.0, sameWrong=2.0, sharePerHeld=0.5, inputTokens=1.5e6, outputTokens=3e5, solved=30.0,
                         **rel, **_slots(nl)))
    return rows
