def perCall21(rows):
    "$ per call by board type from measured rows (the pilot)."
    out = {}
    for r in rows:
        c, n = out.setdefault(boardType(r), [0.0, 0])
        out[boardType(r)] = [c + float(r['cost']), n + int(r['calls'])]
    return {k: c / n for k, (c, n) in out.items() if n}


