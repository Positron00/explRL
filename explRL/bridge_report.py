def _test(dp, nboot, tail='greater'):
    "Estimate (mean), bootSeeds' 95% interval and the uncorrected exact one-sided sign-flip p (tail 'greater' or 'less')."
    est, lo, hi = bootSeeds(dp, nboot=nboot)
    return dict(n=len(dp), estimate=est, ci=[lo, hi], p=signFlipExact(list(dp.values()), tail))


def _lin(a, b, w):
    "The per-board margin a - w x b on the boards both have."
    return {k: a[k] - w * b[k] for k in a if k in b}


def _ratio(a, b, nboot, seed=0):
    "mean(a) / mean(b) over the boards both have, and its 95% interval resampling boards (as bootSeeds)."
    ks = sorted(set(a) & set(b))
    if not ks:
        return NAN, [NAN, NAN]
    r = lambda kk: (lambda d: np.mean([a[k] for k in kk]) / d if d else NAN)(np.mean([b[k] for k in kk]))
    rng = np.random.default_rng(seed)
    bs = [r([ks[j] for j in rng.integers(0, len(ks), len(ks))]) for _ in range(nboot)]
    bs = [x for x in bs if np.isfinite(x)]
    return float(r(ks)), [float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))] if bs else [NAN, NAN]


def gateC1(rows, plan=C1_PLAN, nboot=2000, metric='honestPooled'):
    """Gate C1 on `metric` over the 8 boards (seeds 1800-1807, P20-7). Part (i): bridge1 - colonyGuards, one-sided exact
    sign-flip, passes at p < alpha with a positive estimate. Part (ii), a margin, not a test: mean(bridge1 - colonyGuards) >=
    0.5 x mean(squads - colonyGuards) (the lead), with the per-board margin's interval and uncorrected sign-flip p."""
    s8 = set(plan['seeds']['eight'])
    b, sq = _d(rows, 'bridge1', 'colonyGuards', metric, seeds=s8), _d(rows, 'squads', 'colonyGuards', metric, seeds=s8)
    i = _test(b, nboot)
    i['passes'] = bool(i['p'] < plan['gate']['alpha'] and i['estimate'] > 0)
    lead = _test(sq, nboot)
    ii = dict(_test(_lin(b, sq, 0.5), nboot), lead=lead, bridge=i['estimate'], bar=0.5 * lead['estimate'])
    ii['holds'] = bool(i['estimate'] >= ii['bar'])
    return dict(metric=metric, i=i, ii=ii, passes=bool(i['passes'] and ii['holds']))


