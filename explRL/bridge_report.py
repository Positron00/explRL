def _m(v):
    "Mean of the finite values (NaN, silently, without any)."
    v = [x for x in map(float, v) if np.isfinite(x)]
    return float(np.mean(v)) if v else NAN


def planned20(plan=C1_PLAN):
    "{(level, seed)} of every planned cell at N 64: the new cells with liars and clean (P20-14) and the reused references (P20-6)."
