_MIXINS = dict(trustOne=TrustOne, spread=Spread, shareAll=ShareAll)


@lru_cache(None)
def _b3Class(cls, names):
    return type('B3' + cls.__name__, tuple(_MIXINS[n] for n in names) + (cls,), {})


def b3Members(world, members, seed):
    """FR-A2: each honest numpy member (not a liar or a mistaken member; for an InSquad wrapper, its inner member) gains the
    mixins whose knob is set (trustOne only on counting-board agents, ColonyAgent and its subclasses), with b3Rng(seed, slot);
    guess sets RuleAgent's own argument. Identity, and no generator made, when isDefault. Returns `members`."""
    b3 = dict(world.get('b3') or {})
    if isDefault(b3, world):
        return members
    for slot, m in enumerate(members):
        x = m.m if isinstance(m, InSquad) else m
        if not isinstance(x, RuleAgent) or isinstance(x, (ClueLiar, MistakenAgent)):
            continue
        if b3.get('guess') is not None:
            x.guess = float(b3['guess'])
        names = tuple(n for n in MIXED if b3.get(n) and (n != 'trustOne' or isinstance(x, ColonyAgent)))
        if names:
            x.__class__, x.b3, x.b3rng = _b3Class(type(x), names), b3, b3Rng(seed, slot)
    return members

