def b3Replay(cfg, seed):
    "colony_trace.replay(cfg, seed) for numpy members, with world['b3']'s behaviours -> Replay(rows, [], board, answers, nLiar, T)."
    from explRL.clue_runs import clueMetrics, clueSetup
    from explRL.colony_trace import Replay
    from explRL.llm_agent import runTurns
    from explRL.multi import spawnRngs
    T, nL, w = cfg.turnsPerAgent(), cfg.nLiar, cfg.world
    b, ch = clueSetup(cfg, seed)
    rngs = spawnRngs(seed + 1000, cfg.N)
    members = [faultClass(w)(ch, rngs[i]) if i < nL else memberClass(w, i, nL)(ch, rngs[i]) for i in range(cfg.N)]
    hist = runTurns(b3Members(w, stage4Members(w, members), seed), b, T)
    row = dict(episode=0, **clueMetrics(cfg, b, hist, range(nL, cfg.N), T))
    subs = {(s[0], s[1]) for s in b.submits}
    ans = {(float(r.t), r.agent): r.extras[0] for r in hist.records if (float(r.t), r.agent) in subs}
    return Replay([row], [], b, ans, nL, T)
