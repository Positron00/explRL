class TrustOne:
    """knownFor: the base agent's (so failFlag's flag-aware rule is kept), then for each clue absent from it the leading value
    among values with no failures, when it has fewer than q senders and this agent's draw for (k, j, value) < trustOne."""
    def knownFor(self, b):
        out, q, tal = super().knownFor(b), getattr(self, 'q', Q), tally(self.channel, b)
        fl, seen = failures(b) if getattr(b, 'failFlag', False) else {}, self.__dict__.setdefault('_trust', {})
        for k, cl in tal.items():
            for j, vs in cl.items():
                ok = [v for v in vs if not fl.get((k, j, v[0]))]
                if k in out and j not in out[k] and ok and len(ok[0][1]) < q:
                    if (key := (k, j, ok[0][0])) not in seen:
                        seen[key] = bool(self.b3rng.random() < self.b3['trustOne'])
                    if seen[key]:
                        out[k][j] = ok[0][0]
        return out


class Spread:
    """choose: the base agent's action; if it is an open and the b3 draw < spread, the open goes instead to the live subtask
    with the fewest openers (ties: most known clues, then value, then at random on the b3 generator)."""
    def choose(self, b, t):
        act = super().choose(b, t)
        if act[0] != 'open' or not self.b3rng.random() < self.b3['spread']:
            return act
        kn = self.knownFor(b) if hasattr(self, 'knownFor') else known(self.id, b, self.channel)
        live, n = [x for x in b.open if b.tasks[x].expire > t + 1] or list(b.open), Counter(b.opened)
        key = {x: (n[x] - (b.opened[self.id] == x), -len(kn[x]), -b.tasks[x].value) for x in live}
        top = [x for x in live if key[x] == min(key.values())]
        return ('open', int(top[int(self.b3rng.integers(len(top)))]))


class ShareAll:
    """_shareable(b, kn, t, *a) (GuardAgent passes its subtask order): with probability shareAll this turn, the share policy
    is 'always' for the call (any open subtask, not only one a teammate has open); restored after."""
    def _shareable(self, b, kn, t, *a):
        if not self.b3rng.random() < self.b3['shareAll']:
            return super()._shareable(b, kn, t, *a)
        old, self.share = self.share, 'always'
        try:
            return super()._shareable(b, kn, t, *a)
        finally:
            self.share = old

